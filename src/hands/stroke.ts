/**
 * hands/stroke.ts — одна поправка к кейфреймам замаха.
 *
 * Риг инструмента взят из ядра (`world-core/core`), и камерное Z замаха он
 * множит на СВОЙ `VIEW_Z` - компенсацию узкого обзора рига для мира с обзором
 * 75°, то есть для Snowfall. Здесь мир смотрит на 62°, риг тот же 55°, и
 * компенсация другая: 1.15 против 1.47.
 *
 * Кейфреймы станции записаны сразу в метрах камеры рига (см. `TIP` в лопате и
 * топоре: числа там абсолютные, а не пересчитанные из мирового обзора).
 * Поэтому множитель ядра делим обратно - иначе каждый бросок уходил бы вперёд
 * на треть глубже задуманного, и штык встречал бы прицел не там, где на него
 * поставлен `impact`.
 *
 * Опции «свой VIEW_Z для замаха» у ядра нет; поправка живёт на стороне мира.
 */

import { VIEW_Z, type Keyframe } from 'world-core/core'

/** Разделить дорожку камерного Z на множитель ядра. Кривые входа не трогаем. */
export function pz(track: Keyframe[]): Keyframe[] {
  return track.map((k): Keyframe =>
    k.length === 3 ? [k[0], k[1] / VIEW_Z, k[2]] : [k[0], k[1] / VIEW_Z],
  )
}
