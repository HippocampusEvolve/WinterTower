/**
 * reverb.ts — хвост звука. Место, в котором удар происходит.
 *
 * До сих пор каждый удар рождался и умирал в вакууме: щелчок, тело - и сразу
 * тишина. Так не звучит ничто. Настоящий звук после себя оставляет комнату:
 * сперва несколько отдельных отражений от ближних стен, потом общий гул,
 * который темнеет и гаснет. Ухо по этому хвосту достраивает размер места и
 * материал стен, причём делает это раньше, чем успевает опознать сам удар.
 *
 * Импульсный отклик здесь считается, а не грузится файлом. Готовые отклики
 * лежат в открытых библиотеках и звучат достовернее, но каждый - это ещё один
 * файл в сборке, ещё одна лицензия в NOTICE и ещё одно имя, которое нельзя
 * менять из-за годового кэша. Двадцать строк шума с огибающей дают то, что
 * нужно миру: не концертный зал, а ощущение, что вокруг есть пространство.
 *
 * Считается один раз при запуске звука, за пару миллисекунд.
 */

export type SpaceKind = 'outdoor' | 'indoor'

type Shape = {
  /** Длина хвоста, с. */
  seconds: number
  /** Крутизна спада: больше - дольше держится. */
  decay: number
  /** Ранние отражения: [задержка в мс, громкость]. Они и задают размер места. */
  early: Array<[number, number]>
  /** Насколько быстро темнеет хвост: 0 - не темнеет, 1 - глохнет мгновенно. */
  damp: number
}

/**
 * Два места на выбор.
 *
 * Снаружи станция стоит на открытом склоне: отражений мало, они приходят от
 * ближних построек и мачты, хвост короткий и сильно затемнённый - открытый
 * воздух и снег съедают верх. Внутри бетонная коробка: отражения частые и
 * жёсткие, хвост вдвое длиннее и куда ярче, потому что бетону нечего съедать.
 */
const SHAPES: Record<SpaceKind, Shape> = {
  outdoor: {
    seconds: 0.9,
    decay: 3.2,
    early: [
      [11, 0.5],
      [23, 0.32],
      [41, 0.2],
    ],
    damp: 0.72,
  },
  indoor: {
    seconds: 1.6,
    decay: 2.1,
    early: [
      [7, 0.62],
      [13, 0.48],
      [19, 0.4],
      [29, 0.3],
      [43, 0.22],
    ],
    damp: 0.42,
  },
}

/**
 * Сколько удара уходит в отражения. Снаружи склон почти ничего не возвращает,
 * внутри стены близко и звук приходит обратно заметно громче.
 *
 * Числа живут здесь, а не в `ambient.ts`, потому что их спрашивает ещё и
 * проверка: у неё должен быть тот же мир, а не пересказ его по памяти.
 */
export const SEND: Record<SpaceKind, number> = {
  outdoor: 0.22,
  indoor: 0.4,
}

/**
 * Собрать импульсный отклик.
 *
 * Хвост - это шум под экспоненциальной огибающей, пропущенный через
 * однополюсный фильтр, который к концу закрывается: высокие частоты в любом
 * помещении гаснут первыми, и без этого хвост звучит шипящей полосой, а не
 * воздухом. Каналы считаются порознь - от одинакового шума слева и справа
 * пространство схлопывается в точку между ушами.
 */
export function impulseResponse(ctx: BaseAudioContext, kind: SpaceKind): AudioBuffer {
  const s = SHAPES[kind]
  const len = Math.max(1, Math.floor(ctx.sampleRate * s.seconds))
  const buf = ctx.createBuffer(2, len, ctx.sampleRate)

  for (let c = 0; c < 2; c++) {
    const d = buf.getChannelData(c)
    let lp = 0
    for (let i = 0; i < len; i++) {
      const k = i / len
      const env = Math.pow(1 - k, s.decay)
      // Фильтр закрывается к концу хвоста: место «темнеет», как в жизни.
      const a = 1 - s.damp * (0.35 + 0.65 * k)
      lp += a * ((Math.random() * 2 - 1) * env - lp)
      d[i] = lp
    }

    // Ранние отражения поверх диффузного хвоста. Слева и справа они смещены:
    // одинаковые с обеих сторон читаются эхом в голове, а не комнатой.
    const skew = c === 0 ? 1 : 1.17
    for (const [ms, gain] of s.early) {
      const at = Math.floor((ms * skew * ctx.sampleRate) / 1000)
      if (at < len) d[at] += gain * (c === 0 ? 1 : 0.9)
    }
  }

  return buf
}
