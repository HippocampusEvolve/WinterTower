/**
 * spring.ts — критически задемпфированная пружина, считаемая ТОЧНО.
 *
 * Такая пружина стоит под каждым телесным откликом: отдача камеры от удара,
 * клевок взгляда при приземлении, просадка рук. Уравнение у всех одно:
 * `x'' = -w²·x - 2w·x'` — приходит к нулю без отскока.
 *
 * Считать его пошагово (`v += (-w²x - 2w·v)·dt`) нельзя, и это не вкусовщина.
 * Явная схема устойчива, пока `2w·dt < 2`; при w = 18 это dt < 0.055, а потолок
 * dt в цикле как раз 0.05. То есть на ровных 60 кадрах всё прилично, а на любой
 * просадке — сборка мусора, компиляция шейдера, свёрнутая вкладка — схема
 * входит в раскачку. Замер на боевом сервере поймал ровно это: пик отдачи
 * от одного удара лопатой 0.82 рад (47°!) вместо расчётных 0.035 (2°).
 * Камеру швыряло тем сильнее, чем хуже шёл кадр.
 *
 * Здесь вместо шага берётся решение уравнения в лоб:
 *   x(t) = (x₀ + (v₀ + w·x₀)·t)·e^(−w·t)
 * Оно верно при любом dt, и на большом шаге даёт не взрыв, а просто более
 * быстрое затухание.
 */

export type Spring = { x: number; v: number }

/** Продвинуть пружину на `dt`. `w` — жёсткость, 1/с (полное оседание ≈ 4/w). */
export function stepSpring(s: Spring, w: number, dt: number) {
  const b = s.v + w * s.x
  const e = Math.exp(-w * dt)
  s.x = (s.x + b * dt) * e
  s.v = (s.v - w * b * dt) * e
}
