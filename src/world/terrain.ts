/**
 * terrain.ts — скальный гребень.
 *
 * Форма собирается из четырёх слагаемых, и каждое отвечает за свой слой референса:
 *   1. crestY(z)    — профиль гребня вдоль взгляда: терраса → седловина → даль;
 *   2. crossFall(d) — поперечный срез: плато со зданиями, слева обрыв в пустоту;
 *   3. взлобок      — гауссов холм, на котором стоит купол (иначе он тонет за гребнем);
 *   4. detail()     — шум, амплитуда растёт к обрывам: плато остаётся ходибельным.
 *
 * `heightAt` — единственный источник правды о земле. По ней ставится весь реквизит
 * и по ней же считаются коллизии игрока (см. player.ts). Рельеф в Octree НЕ кладём:
 * 100k треугольников в дереве не нужны, аналитическая высота точнее и бесплатна.
 */

import * as THREE from 'three'
import { PALETTE } from '../atmosphere'
import { LAKE, type Spot } from './layout'
import { MAT } from './materials'

// --- Размеры полотна --------------------------------------------------------
// Смещено в -Z: игрок смотрит туда, туда же нужен запас. При fogDensity 0.012
// дальний край на 230 м полностью съеден туманом — границы плоскости не видно.
const SIZE = 460
const SEG = 300 // ячейка ~1.5 м: мельче скальные складки сетка уже не держит
const CENTER_Z = -80

/**
 * Общий множитель яркости камня. Отдельным числом, потому что подбирается
 * замером против референса в паре с `SETTINGS.fogDensity` — это две ручки
 * одной задачи, и крутить их надо вместе (см. вершинную раскраску ниже).
 */
const ROCK_LIFT = 1.4

// --- Шум --------------------------------------------------------------------

function hash2(i: number, j: number): number {
  const n = Math.sin(i * 127.1 + j * 311.7) * 43758.5453
  return n - Math.floor(n)
}

/** Value-noise, 0..1. Дёшево и детерминированно — этого достаточно. */
function noise2(x: number, y: number): number {
  const i = Math.floor(x)
  const j = Math.floor(y)
  const fx = x - i
  const fy = y - j
  const sx = fx * fx * (3 - 2 * fx)
  const sy = fy * fy * (3 - 2 * fy)
  const a = hash2(i, j)
  const b = hash2(i + 1, j)
  const c = hash2(i, j + 1)
  const d = hash2(i + 1, j + 1)
  return (a + (b - a) * sx) * (1 - sy) + (c + (d - c) * sx) * sy
}

/** Сумма октав, 0..1. */
function fbm(x: number, y: number, octaves: number): number {
  let amp = 0.5
  let freq = 1
  let sum = 0
  let norm = 0
  for (let i = 0; i < octaves; i++) {
    sum += noise2(x * freq, y * freq) * amp
    norm += amp
    amp *= 0.5
    freq *= 2
  }
  return sum / norm
}

/** То же, но центрировано в -1..1. */
const snoise = (x: number, y: number, o: number) => (fbm(x, y, o) - 0.5) * 2

// --- Профиль гребня ---------------------------------------------------------

/**
 * Высота гребня по Z. Точки идут от «за спиной игрока» вдаль.
 * Читается как разрез вдоль кадра референса: игрок наверху, станция уходит
 * вниз-вдаль, в середине провал, за ним поднимается площадка обсерватории.
 *
 * Датум фазы 3.6: **дорожка под камерой = 0**. Все высоты в файле — от неё,
 * потому что все замеры по референсу сняты именно в этой системе
 * (см. `docs/SCALE.md`). Прежний профиль был вдвое «выше» человека:
 * камера стояла в 8.4 м над дорожкой при замеренных 4.0.
 *
 * Фаза 3.8 сжала профиль по глубине. Кадр от абсолютной дистанции не зависит
 * вовсе (`docs/SCALE.md` §2: купол Ø24 на 90 м и Ø16 на 60 м попиксельно
 * одинаковы), зависит только туман — а он съедал дальнюю скалу на 64%.
 * Карта сжатия к глазу двухзонная, и зоны разные не из красоты:
 *   ближнее поле (z ≥ −45) — только по Z, коэффициент 0.62. Высоты здесь
 *     приколочены человеком (дверь 2.1 м, корпус 4.9 м, камера 4.0 м над
 *     дорожкой), а длина дорожки вдоль взгляда — ничем;
 *   дальнее (z ≤ −70) — подобием, 0.70: там кадр не задаёт масштаб совсем.
 * Числа пересчитаны зондом на настоящей `heightAt`, не рукой.
 */
const CREST: ReadonlyArray<readonly [number, number]> = [
  [40.4, -14],
  [19.3, 2.2],
  [10.6, 1.3], // терраса, откуда стартует игрок
  [-0.5, 0.2],
  [-12.9, -1.2],
  [-24.1, -2.4], // седловина, здесь кончается дорожка и начинается марш
  // Дальше склон поднимается к обсерватории РАВНОМЕРНО.
  // Это не украшательство, а требование: лестница идёт под 32° (подступенок
  // 0.19 / проступь 0.3), и на 60-градусном обрыве она превращается в эстакаду,
  // висящую на десяток метров над землёй, — сесть на неё негде.
  // Сжатие уклон сохранило: подъём к полке шёл 0.36 м/м, стал 0.38.
  [-33.6, 2.3],
  [-43.3, 6.9],
  [-50.7, 11.0],
  [-61.9, 11.8], // полка обсерватории
  [-70.3, 7.5],
  [-88.5, -3.0],
  [-123.5, -19.8],
  [-193.5, -40.8],
]

function crestY(z: number): number {
  if (z >= CREST[0][0]) return CREST[0][1]
  const last = CREST[CREST.length - 1]
  if (z <= last[0]) return last[1]
  for (let i = 1; i < CREST.length; i++) {
    const [z1, y1] = CREST[i]
    if (z >= z1) {
      const [z0, y0] = CREST[i - 1]
      const t = (z - z1) / (z0 - z1)
      return y1 + (y0 - y1) * (t * t * (3 - 2 * t))
    }
  }
  return last[1]
}

/** Линия гребня по X: лёгкий меандр, чтобы хребет не был линейкой. */
const crestX = (z: number) => 8 + Math.sin(z * 0.017) * 3.5 - z * 0.02

// Ширина плато от линии гребня. Слева узко — дорожка и сразу обрыв,
// справа широко — здания и хозяйственный двор за ними.
const PLATEAU_L = 7
const PLATEAU_R = 30

/**
 * Насколько земля просела относительно гребня на расстоянии d от него.
 *
 * Левый борт нарастает медленно (≈17° у бровки) и разгоняется вглубь (≈40° внизу).
 * Два требования, оба жёсткие:
 *   — уклон должен только расти, иначе бровка перекрывает собственный склон
 *     и лестница со скалой пропадают из кадра целиком;
 *   — падать он должен медленно. С крутым бортом скала обрывается в туман
 *     через 20 м, и вместо каменного массива на пол-кадра остаётся полоска.
 */
function crossFall(d: number): number {
  if (d < -PLATEAU_L) {
    // Фаза 3.6: борт стал настоящим обрывом. Прежние 17° у бровки давали
    // пологий скат, по которому лестница спускалась «в поле»; по референсу
    // слева от дорожки — скальная стена, и низ марша уходит на 16 м вниз
    // всего в 18 м от линии гребня.
    const t = -d - PLATEAU_L
    return t * 0.9 + Math.pow(t, 1.6) * 0.06
  }
  if (d > PLATEAU_R) {
    const t = d - PLATEAU_R
    return t * 0.85 + Math.pow(t, 1.5) * 0.05
  }
  return Math.abs(d) * 0.04
}

// Полка обсерватории: горизонтальная площадка, на которой стоит весь комплекс.
//
// Высота 11.8 м над дорожкой — не на глаз: пол комплекса стоит на экране
// в y=250 при горизонте 324 (`docs/SCALE.md`), а это УГОЛ, а не высота.
// До фазы 3.8 тот же угол давали 15.1 м на 90 м; после сжатия дальнего плана
// подобием (0.70) его дают 11.8 м на 63 м. Кадр не изменился ни на пиксель,
// изменилось то, сколько тумана лежит между глазом и полкой.
// Отдельный «взлобок» гауссианой убран: высоту теперь даёт сам профиль гребня
// (`CREST`), а полка только срезает макушку в горизонталь. Одна сущность вместо
// двух, и не нужно бороться с длинным хвостом гауссианы.
//
// Форма — скруглённый прямоугольник (`max` по осям, не `hypot`): эллипс срезает
// углы ровно там, где стоят дальние углы зданий. Ровная часть — до q 0.75,
// это x −22…+14 и z −66…−49: комплекс длиной 21 м помещается целиком.
// Кромка от 0.75 до 1.2 даёт скальный уступ под обсерваторией — он на референсе
// и есть, лестница спускается по нему.
const SHELF_X = -4.15
const SHELF_Z = -57.7
const SHELF_RX = 23.8
const SHELF_RZ = 11.2
const SHELF_Y = 11.8

/**
 * «Насколько это борт, а не плато»: 0 — ровная площадка станции, 1 — скальный склон.
 * Один и тот же признак задаёт и амплитуду скальных складок, и то, держится ли
 * здесь снег. Ramp узкий: с широким ближняя часть склона остаётся гладкой и белой,
 * а именно она занимает нижнюю треть кадра.
 */
export function flankAt(x: number, z: number): number {
  const d = x - crestX(z)
  return Math.max(
    THREE.MathUtils.smoothstep(-d, PLATEAU_L - 2, PLATEAU_L + 6),
    THREE.MathUtils.smoothstep(d, PLATEAU_R - 2, PLATEAU_R + 10),
  )
}

/**
 * Шум рельефа. На плато почти нулевой, к обрывам разрастается в скальные складки.
 * Верхняя частота — 0.16 (длина волны ~6 м, вчетверо крупнее ячейки). Всё, что
 * мельче, сетка не воспроизводит: шум исчезает, и скала выходит гладким чехлом.
 *
 * Последнее слагаемое — **кулуары**, и оно не изотропное.
 *
 * После фазы 3.6 борт стал круче (0.9·t вместо 0.3·t), и левая половина кадра
 * превратилась в гладкую белую стену. Дело было не в амплитуде: изотропный шум
 * с невязкой ±0.3 м на базе 6 м на склоне в 50° не читается вообще никак —
 * складка обязана быть длиннее, чем шире. У настоящего борта борозды идут
 * ПО ЛИНИИ ПАДЕНИЯ, то есть вдоль X (гребень тянется вдоль Z). Отсюда разные
 * частоты по осям: 0.105 по Z (борозда шириной ~10 м) против 0.017 по X
 * (длина ~60 м). Множитель `flank` держит плато и дорожку чистыми.
 */
function detail(x: number, z: number, flank: number): number {
  return (
    snoise(x * 0.022, z * 0.022, 4) * (0.28 + flank * 6) +
    snoise(x * 0.075, z * 0.075, 3) * (0.16 + flank * 3.2) +
    snoise(x * 0.16, z * 0.16, 2) * (0.08 + flank * 1.6) +
    snoise(x * 0.017, z * 0.105, 2) * flank * 5.0
  )
}

/** Высота земли в мировых координатах. Весь реквизит ставится по ней. */
export function heightAt(x: number, z: number): number {
  const d = x - crestX(z)
  const flank = flankAt(x, z)

  const h = crestY(z) - crossFall(d) + detail(x, z, flank)

  // Полка срезает макушку в горизонталь. Идёт последней: шум под ней тоже
  // сглаживается, иначе площадка обсерватории остаётся волнистой и здания
  // на ней снова начинают качаться.
  //
  // И ровно в этом была «гладкая белая стена» из открытых проблем. Скат полки
  // занимает половину левой стороны кадра, а бленд к константе стирает под
  // собой весь рельефный шум — получалась безупречная бетонная чаша, и никакая
  // добавка в `detail()` этого не лечила, потому что стиралась вместе с ним.
  //
  // Лечится в два хода, оба только на скате, плита остаётся идеально ровной:
  //   — плановая граница полки гуляет шумом, иначе кромка читается лекалом;
  //     возмущение включается только за q≈0.72, чтобы пятна зданий не поехали;
  //   — на самом скате (k между 0 и 1) возвращаются кулуары той же анизотропией,
  //     что и на борту: борозды вдоль линии падения.
  const q0 = Math.max(Math.abs(x - SHELF_X) / SHELF_RX, Math.abs(z - SHELF_Z) / SHELF_RZ)
  const q = q0 + snoise(x * 0.035, z * 0.035, 2) * 0.11 * THREE.MathUtils.smoothstep(q0, 0.72, 1.0)
  const k = 1 - THREE.MathUtils.smoothstep(q, 0.75, 1.2)
  const skirt = k * (1 - k) * 4 // 0 на плите и у подножия, 1 в середине ската
  const g = h + (SHELF_Y - h) * k + snoise(x * 0.03, z * 0.11, 2) * skirt * 3.2

  // Дно мира — лёд озера. Одна строка вместо котлована с бортами: озеро не
  // вырезается в рельефе, а ЗАЛИВАЕТ его снизу, и берег получается там, где
  // склон сам пересекает отметку воды. Отсюда изрезанная кромка даром.
  //
  // Заливка идёт последней и намеренно ничего не сглаживает: сглаженный стык
  // дал бы пляж по всему периметру, а на горном озере берег — это скала,
  // входящая в лёд под своим углом.
  return Math.max(LAKE.y, g)
}

/** Крутизна склона: 0 — горизонталь, 1 — 45°, дальше больше. */
export function slopeAt(x: number, z: number): number {
  const e = 1.2
  return Math.hypot(
    (heightAt(x + e, z) - heightAt(x - e, z)) / (2 * e),
    (heightAt(x, z + e) - heightAt(x, z - e)) / (2 * e),
  )
}

/**
 * Пол здания: по самой высокой точке пятна плюс собственный подъём пятна.
 *
 * Живёт здесь, а не в `buildings.ts`, потому что ту же отметку спрашивают ещё
 * трое: короба на крышах (`props.ts`), проверка компоновки и замерялка. Копия
 * формулы в `tools/measure.ts` уже была — ровно тот класс расхождения, ради
 * которого заведён `layout.ts`.
 */
export function floorOf(s: Spot): number {
  return highestIn(s.x0, s.x1, s.z0, s.z1) + 0.35 + (s.lift ?? 0)
}

/** Максимум высоты по углам прямоугольника — чтобы посадить здание, а не утопить его. */
export function highestIn(x0: number, x1: number, z0: number, z1: number): number {
  let hi = -Infinity
  for (let i = 0; i <= 4; i++) {
    for (let j = 0; j <= 4; j++) {
      const h = heightAt(x0 + ((x1 - x0) * i) / 4, z0 + ((z1 - z0) * j) / 4)
      if (h > hi) hi = h
    }
  }
  return hi
}

/** Минимум — чтобы цоколь дотянулся до земли на низком краю. */
export function lowestIn(x0: number, x1: number, z0: number, z1: number): number {
  let lo = Infinity
  for (let i = 0; i <= 4; i++) {
    for (let j = 0; j <= 4; j++) {
      const h = heightAt(x0 + ((x1 - x0) * i) / 4, z0 + ((z1 - z0) * j) / 4)
      if (h < lo) lo = h
    }
  }
  return lo
}

// --- Меш --------------------------------------------------------------------

export function buildTerrain(): THREE.Mesh {
  const geo = new THREE.PlaneGeometry(SIZE, SIZE, SEG, SEG)
  // Кладём плоскость сразу в мировую ориентацию: дальше x/z читаются напрямую,
  // без трюка «локальный y это -z», на котором в фазе 1 утонул весь реквизит.
  geo.rotateX(-Math.PI / 2)
  geo.translate(0, 0, CENTER_Z)

  const pos = geo.attributes.position as THREE.BufferAttribute
  for (let i = 0; i < pos.count; i++) {
    pos.setY(i, heightAt(pos.getX(i), pos.getZ(i)))
  }
  pos.needsUpdate = true
  geo.computeVertexNormals()

  // Вогнутость: насколько точка ниже среднего своих четырёх соседей.
  // Считается ПО СЕТКЕ, а не новыми вызовами `heightAt`, — высоты уже посчитаны,
  // и четыре лишних обращения к fbm на каждую из 90 тысяч вершин стоили бы
  // секунду на старте ради того же самого числа.
  //
  // Нужна она снегу: он держится не там, где полого, а там, где его не сдувает —
  // в кулуарах, за перегибами, в карманах между складок. Уклон этого не знает.
  const W = SEG + 1
  const curv = new Float32Array(pos.count)
  for (let r = 1; r < SEG; r++) {
    for (let cIdx = 1; cIdx < SEG; cIdx++) {
      const i = r * W + cIdx
      const avg =
        (pos.getY(i - 1) + pos.getY(i + 1) + pos.getY(i - W) + pos.getY(i + W)) / 4
      curv[i] = avg - pos.getY(i)
    }
  }

  // Снег держится на пологом, на отвесах остаётся мокрая тёмная скала.
  // Это единственное «не серый бокс» в фазе 2, но без него левая половина
  // кадра — сплошное белое пятно, и композиция референса не читается.
  const nrm = geo.attributes.normal as THREE.BufferAttribute
  const colors = new Float32Array(pos.count * 3)
  const c = new THREE.Color()
  const s = new THREE.Color()
  const rockA = new THREE.Color(PALETTE.rockDark)
  const rockB = new THREE.Color(PALETTE.rockLight)
  const snowA = new THREE.Color(PALETTE.snowShadow)
  const snowB = new THREE.Color(PALETTE.snowLit)
  const iceA = new THREE.Color(PALETTE.iceDark)
  const iceB = new THREE.Color(PALETTE.iceLight)

  for (let i = 0; i < pos.count; i++) {
    const x = pos.getX(i)
    const z = pos.getZ(i)
    // Снег ложится не по чистому уклону, а пятнами: на референсе борт — это
    // тёмная скала с белыми языками в кулуарах, а не белый склон с чёрными швами.
    //
    // Одного уклона мало: борт пришлось выположить ради видимости, и по нормали
    // он теперь неотличим от площадки. Поэтому решает не только наклон, но и
    // сама принадлежность к борту (flankAt) — открытый ветру камень снега не держит.
    const ny = nrm.getY(i)
    const flat = THREE.MathUtils.smoothstep(ny, 0.93, 0.995)
    // Три масштаба: крупные поля снега, языки в кулуарах и мелкая рвань кромки.
    // Третье слагаемое короче ячейки сетки и потому не лепит форму — оно только
    // рвёт ГРАНИЦУ между камнем и снегом, а её сетка держит: граница живёт
    // в цвете вершин, а не в геометрии.
    const patch =
      (snoise(x * 0.045, z * 0.045, 3) * 0.26 +
        snoise(x * 0.13, z * 0.13, 2) * 0.12 +
        snoise(x * 0.42, z * 0.42, 2) * 0.05) *
      (1 - flat)
    // Открытый ветру борт снега не держит.
    const exposed = flankAt(x, z) * 0.15
    // Снег копится в карманах и сдувается с рёбер. Поправка обязана быть
    // СИММЕТРИЧНОЙ: первый заход давал от −0.05 до +0.14, и весь борт побелел —
    // добавка работала не «карманом», а общей прибавкой снега везде.
    const pocket = THREE.MathUtils.clamp(curv[i] * 1.2, -0.07, 0.07)
    // Переход сужен с 0.88…0.97 при той же середине 0.925: на референсе кромка
    // снега резкая, размытая граница читается не снегом, а грязным градиентом.
    const t = THREE.MathUtils.smoothstep(ny + patch - exposed + pocket, 0.9, 0.95)

    // Частота 0.19 давала длину волны 5 м — вдвое мельче ячейки сетки (2 м),
    // то есть шум просто пропадал, и камень выходил одноцветной плёнкой.
    //
    // Смесь идёт через `smoothstep`, а не по сырому fbm: у нормированного fbm
    // значения жмутся к середине, и камень получался ровно среднего тона по
    // всей скале. Кривая разводит его на светлые плиты и тёмные промоины —
    // ту самую пятнистость, по которой глаз и узнаёт камень.
    // Вторая, мелкая октава кладётся ПОВЕРХ: длина волны 3 м, вдвое крупнее
    // ячейки. Геометрию такой шум уже не лепит (её сетка не держит), а цвет
    // вершин — держит, и склон перестаёт быть заливкой одного тона.
    const grain = THREE.MathUtils.smoothstep(
      fbm(x * 0.055, z * 0.055, 3) + snoise(x * 0.33, z * 0.33, 2) * 0.13,
      0.32,
      0.68,
    )
    c.copy(rockA).lerp(rockB, grain)
    // Дешёвое затенение складок: чем круче грань, тем она темнее.
    //
    // Числа сведены замером против референса, а не на глаз. Разрыв был в
    // ближней скале: 0.425 от яркости тумана при 0.618 на картинке — самый
    // большой во всём кадре. Общий множитель его не лечит: он тянет вверх
    // ВЕСЬ склон, а средняя и дальняя скала уже стояли в мишени и уезжали
    // выше неё. Поэтому поднят «пол» затенения (0.72 → 0.95), а разброс по
    // нормали сжат (0.38 → 0.2): светлеют именно крутые грани, из которых
    // и состоит ближний борт, а пологие остаются на месте.
    //
    // Физически это честнее прежнего: в плотном тумане свет приходит со всех
    // сторон разом, и отвес затеняется куда слабее, чем под открытым небом.
    // Затенение по вогнутости — тот же `curv`, что решает судьбу снега.
    // Это запечённый AO рельефа, и без него левый борт читается ровной заливкой
    // при полностью правильной яркости: замер держал 0.75 от тумана при мишени
    // 0.72, а глаз всё равно видел плёнку. Разницу делает не средний тон,
    // а то, что промоины темнее рёбер.
    const crease = 1 - THREE.MathUtils.clamp(curv[i] * 0.9, -0.12, 0.18)
    c.multiplyScalar(ROCK_LIFT * (0.95 + 0.2 * ny) * crease)
    s.copy(snowA).lerp(snowB, fbm(x * 0.05, z * 0.05, 2))
    c.lerp(s, t)

    // Лёд озера рельеф не красит: он ловит небо зеркалом, а материал земли
    // матовый (roughness 0.94). Сам лёд — отдельная поверхность, `lake.ts`.
    // Здесь только то, что под ней: дно у самого берега, где лёд кончается.
    if (pos.getY(i) <= LAKE.y + 0.01) c.copy(iceA).lerp(iceB, 0.35)

    colors[i * 3] = c.r
    colors[i * 3 + 1] = c.g
    colors[i * 3 + 2] = c.b
  }
  geo.setAttribute('color', new THREE.BufferAttribute(colors, 3))

  // UV в метры, как у всей остальной статики (`planarUV` в `parts.ts`):
  // у `PlaneGeometry` они идут 0…1 на всё полотно, а материал ждёт метры.
  const uv = geo.attributes.uv as THREE.BufferAttribute
  for (let i = 0; i < uv.count; i++) uv.setXY(i, uv.getX(i) * SIZE, uv.getY(i) * SIZE)

  const mesh = new THREE.Mesh(geo, MAT.ground)
  mesh.name = 'terrain'
  return mesh
}
