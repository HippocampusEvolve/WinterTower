/**
 * interior.ts — помещения: стены с проёмами, внутренние лестницы, реестр объёмов.
 *
 * Зачем отдельный модуль. До фазы 5 заходимое помещение было ровно одно
 * (дежурка), и оно было выписано руками прямо в `buildings.ts`: пять слэбов,
 * огибающих пустоту. Как только помещений стало пять, ручная сборка перестала
 * читаться — половина строк в файле оказывалась арифметикой простенков.
 * Абстракция вводится по правилу проекта: её потребовали ДВА реальных случая
 * (служебный корпус и купол), а не «на будущее».
 *
 * Три вещи, ради которых он существует:
 *
 * 1. **Стена с проёмами** (`wall`). Проём в стене — это не вычитание, а три
 *    куска: простенок слева, простенок справа, перемычка сверху (и подоконная
 *    часть снизу, если проём — окно). CSG по-прежнему в отвергнутых идеях:
 *    у коробок нет вывернутых нормалей, и всё уходит в Octree как есть.
 * 2. **Реестр внутренних объёмов** (`Interiors`). Снег внутри комнаты и ветер
 *    той же громкости, что на улице, — оба дефекта чинятся одним вопросом
 *    «игрок под крышей?». Ответ нельзя вычислить из рельефа: пол помещения
 *    задаётся зданием. Поэтому объёмы регистрируются там, где строятся.
 * 3. **Внутренняя лестница** (`flight`). Секции корпуса стоят ступеньками вниз
 *    по гребню, и полы у них разные: 1.85, 0.25, −1.15. Сквозной коридор
 *    обязан эту разницу собирать, иначе проём между секциями превращается
 *    в полутораметровый уступ, который капсула не переступает.
 *
 * Внимание к `wall`: координата `at` — это НАЧАЛО толщины, стена занимает
 * `at … at + t`. Знак толщины важен, когда стена ограничивает комнату: класть
 * её надо наружу от полезного объёма, иначе комната потихоньку съедается.
 */

import type { Parts } from './parts'

/** Проём в стене. `at` — центр вдоль стены, `sill` — низ проёма над полом. */
export type Hole = { at: number; w: number; h: number; sill?: number }

/**
 * Внутренний объём: прямоугольник в плане плюс отметки пола и потолка.
 *
 * `y0` регистрируется РОВНО на 0.5 ниже пола — по этому соглашению `npm run room`
 * находит отметку пола, и отклонение на 10 см показывает всю обстановку
 * «ушедшей под пол».
 *
 * `r` задаётся только круглым помещениям (зал обсерватории — единственное):
 * рамка тогда описанный квадрат, а стена — круг радиуса `r` вокруг её центра.
 * Без этого поля круглый зал приходилось вписывать в квадрат со стороной 0.85
 * от диаметра — то есть рамка была УЖЕ стены по осям и ШИРЕ по диагоналям:
 * снег не шёл там, где нет крыши, а проверка «предмет в стене» пропускала
 * шкаф, воткнутый в барабан.
 */
export type Room = {
  name: string
  x0: number
  x1: number
  z0: number
  z1: number
  y0: number
  y1: number
  r?: number
}

/** Внутри круглой стены помещения? Для прямоугольных — всегда да. */
export function inRound(r: Room, x: number, z: number, pad = 0): boolean {
  if (r.r === undefined) return true
  const cx = (r.x0 + r.x1) / 2
  const cz = (r.z0 + r.z1) / 2
  const lim = r.r - pad
  return (x - cx) * (x - cx) + (z - cz) * (z - cz) < lim * lim
}

/**
 * Реестр помещений. Отвечает на единственный вопрос: точка под крышей или нет.
 *
 * Проверка нарочно грубая — прямоугольные объёмы, никакой геометрии. Точность
 * тут не нужна: цена ошибки — хлопья снега в дверном проёме, а не проваленный
 * пол. Зато она стоит десяток сравнений и её можно звать на каждую снежинку.
 */
export class Interiors {
  readonly rooms: Room[] = []

  add(r: Room): Room {
    this.rooms.push(r)
    return r
  }

  /** Точка внутри какого-нибудь помещения? `pad` сужает объём (отрицательный — расширяет). */
  contains(x: number, y: number, z: number, pad = 0): boolean {
    for (const r of this.rooms) {
      if (
        x > r.x0 + pad &&
        x < r.x1 - pad &&
        z > r.z0 + pad &&
        z < r.z1 - pad &&
        y > r.y0 - 0.2 &&
        y < r.y1 + 0.2 &&
        inRound(r, x, z, pad)
      ) {
        return true
      }
    }
    return false
  }

  /** Имя помещения под точкой — для отладки через `wt.world.roomAt(...)`. */
  nameAt(x: number, y: number, z: number): string | null {
    for (const r of this.rooms) {
      if (
        x > r.x0 &&
        x < r.x1 &&
        z > r.z0 &&
        z < r.z1 &&
        y > r.y0 - 0.2 &&
        y < r.y1 + 0.2 &&
        inRound(r, x, z)
      ) {
        return r.name
      }
    }
    return null
  }
}

/**
 * Стена вдоль оси с проёмами.
 *
 * `axis` — вдоль какой оси тянется стена; `from`..`to` — её концы по этой оси;
 * `at`..`at + t` — положение поперёк; `y`..`y + h` — по высоте.
 * Проёмы задаются в тех же координатах, что `from`/`to`.
 */
export function wall(
  p: Parts,
  o: {
    axis: 'x' | 'z'
    from: number
    to: number
    at: number
    t: number
    y: number
    h: number
    holes?: Hole[]
  },
): void {
  const { axis, at, t, y, h } = o
  const a = Math.min(o.from, o.to)
  const b = Math.max(o.from, o.to)
  const c0 = Math.min(at, at + t)
  const c1 = Math.max(at, at + t)

  /** Кусок стены: от `u0` до `u1` вдоль оси, от `v` вверх на `vh`. */
  const piece = (u0: number, u1: number, v: number, vh: number) => {
    if (u1 - u0 < 0.01 || vh < 0.01) return
    if (axis === 'x') p.slab(u0, u1, c0, c1, v, vh)
    else p.slab(c0, c1, u0, u1, v, vh)
  }

  const holes = (o.holes ?? [])
    .filter((q) => q.at + q.w / 2 > a && q.at - q.w / 2 < b)
    .sort((q, r) => q.at - r.at)

  let u = a
  for (const q of holes) {
    const l = Math.max(a, q.at - q.w / 2)
    const r = Math.min(b, q.at + q.w / 2)
    piece(u, l, y, h) // простенок до проёма
    const sill = q.sill ?? 0
    if (sill > 0.01) piece(l, r, y, sill) // подоконная часть
    const top = sill + q.h
    if (h - top > 0.01) piece(l, r, y + top, h - top) // перемычка
    u = r
  }
  piece(u, b, y, h)
}

/**
 * Марш внутри здания: собирает перепад между полами соседних секций.
 *
 * Идёт вдоль оси от `start` в сторону `sign`, спускаясь с `yTop` на `yBottom`.
 * Ступень 0.2 × 0.32 — чуть положе уличной (0.19 × 0.30): внутри марш короткий,
 * а лишний сантиметр подступенка на восьми ступенях даёт четверть метра длины.
 *
 * Возвращает координату подножия по ходовой оси — за неё цепляется пол площадки.
 */
export function flight(
  p: Parts,
  o: {
    axis: 'x' | 'z'
    /** Поперечные границы марша (по другой оси). */
    w0: number
    w1: number
    /** Начало марша по ходовой оси и направление (+1 / −1). */
    start: number
    sign: 1 | -1
    yTop: number
    yBottom: number
  },
): number {
  const RISE = 0.2
  const RUN = 0.32
  const n = Math.max(1, Math.round((o.yTop - o.yBottom) / RISE))
  const rise = (o.yTop - o.yBottom) / n
  for (let i = 0; i < n; i++) {
    const u0 = o.start + o.sign * i * RUN
    const u1 = u0 + o.sign * RUN
    // ВЕРХ ступени, а не низ. Первая ступень у стены лежит вровень с полом
    // верхней секции — с неё и сходишь из проёма; дальше вглубь каждая ниже
    // на подступенок. Ступень — толстая плита до пола нижнего уровня: под
    // маршем ничего нет, и тонкие проступи изнутри читались бы досками.
    const top = o.yTop - i * rise
    if (o.axis === 'z') p.slab(o.w0, o.w1, Math.min(u0, u1), Math.max(u0, u1), o.yBottom, top - o.yBottom)
    else p.slab(Math.min(u0, u1), Math.max(u0, u1), o.w0, o.w1, o.yBottom, top - o.yBottom)
  }
  return o.start + o.sign * n * RUN
}
