/**
 * Парапет по периметру крыши.
 *
 * Снега здесь больше нет ни одной плитой, и это правка фазы 10: и полотно
 * внутри парапета, и шапки на самом парапете рисует снежный слой в шейдере
 * (`snowify` в `materials.ts`). Плита внутри парапета была ещё и лишней
 * поверхностью в 16 см над крышей — вторым полом, спорящим с первым.
 */
function roofCap(x0: number, x1: number, zLo: number, zHi: number, top: number) {
  const P = 0.32
  dark.slab(x0, x1, zLo, zLo + P, top, 0.55)
  dark.slab(x0, x1, zHi - P, zHi, top, 0.55)
  dark.slab(x0, x0 + P, zLo, zHi, top, 0.55)
  dark.slab(x1 - P, x1, zLo, zHi, top, 0.55)
}

/** Коробка с парапетом и снежной шапкой на крыше. */
function shell(x0: number, x1: number, z0: number, z1: number, floor: number, h: number) {
  const zLo = Math.min(z0, z1)
  const zHi = Math.max(z0, z1)
  walls.slab(x0, x1, zLo, zHi, floor, h)
  roofCap(x0, x1, zLo, zHi, floor + h)
}

/**
 * Цоколь: от пола вниз до земли. На низком краю читается подпорной стенкой.
 *
 * Ограничение глубины держалось за то, что на крутом взлобке под куполом дно
 * уходило на десяток метров и вместо тёмной скалы вырастал белый бетонный утёс.
 * Лечили не ту болезнь: при `maxDepth` 4.5 цоколь купола обрывался на 6.8 м
 * ВЫШЕ земли — здание висело в воздухе. Правильное лекарство — полка под
 * обсерваторией (см. terrain.ts), после неё перепад везде меньше трёх метров,
 * а предел остаётся страховкой от новых кривых пятен.
 */
function plinth(x0: number, x1: number, z0: number, z1: number, floor: number, maxDepth = 9) {
  const bottom = Math.max(
    lowestIn(x0, x1, Math.min(z0, z1), Math.max(z0, z1)) - 2.5,
    floor - maxDepth,
  )
  dark.slab(x0 - 0.25, x1 + 0.25, Math.min(z0, z1), Math.max(z0, z1), bottom, floor - bottom)
}

/**
 * Окно на стене, смотрящей в -X. Плоскость чуть впереди стены.
 * `kind`: 0 — тёмное, 1 — светлое тёмное (другая комната), 2 — горит свет.
 */
function windowXneg(x: number, y: number, z: number, w: number, h: number, kind: 0 | 1 | 2) {
  const target = kind === 2 ? lit : kind === 1 ? pale : glass
  target.add(new THREE.PlaneGeometry(w, h), x - 0.03, y, z, 0, -Math.PI / 2, 0)
  // Рама тонкая и светлая. Стена смотрит в -X, поэтому ширина окна лежит по Z:
  // верх/низ — перемычки, тонкие по Y и длинные по Z, боковины наоборот.
  const F = 0.055
  metal.box(0.08, F, w + F * 2, x - 0.02, y + h / 2 + F / 2, z)
  metal.box(0.08, F, w + F * 2, x - 0.02, y - h / 2 - F / 2, z)
  metal.box(0.08, h + F * 2, F, x - 0.02, y, z - w / 2 - F / 2)
  metal.box(0.08, h + F * 2, F, x - 0.02, y, z + w / 2 + F / 2)
  // Переплёт: вертикальный импост и горизонтальная планка. Без него светящееся
  // окно вблизи — ровный жёлтый прямоугольник, а тёмное — ровный синий.
  // Делит стекло на створки, то есть делает его окном, а не проёмом.
  metal.box(0.07, h, 0.045, x - 0.02, y, z)
  metal.box(0.07, 0.04, w, x - 0.02, y + h * 0.16, z)
  // Наружный отлив. Без него окно — наклейка на плоской стене: толщину ей
  // даёт не рама, а выступ под ней, ловящий свет сверху. Снег на отлив и на
  // верхнюю планку рамы кладёт шейдерный слой — накладных плит здесь больше
  // нет, они были 4 см высотой и читались белой полосой поперёк рамы.
  const OUT = 0.16
  dark.box(OUT, 0.05, w + F * 2, x - OUT / 2, y - h / 2 - F, z)
}

/**
 * То же окно в стене, смотрящей в +Z (торец центрального корпуса).
 *
 * Второй случай, а не обобщение первого: ось поворота, знак выноса отлива и
 * порядок сторон у рамы разные, и функция «окно по любой оси» вышла бы длиннее
 * двух прямых. Правило проекта — абстракцию вводить, когда её потребовали два
 * случая; здесь их ровно два, и оба короткие.
 *
 * `z` — наружная грань стены, стена занимает `z − t … z`.
 */
function windowOpenZ(z: number, t: number, y: number, x: number, w: number, h: number) {
  piece('окно', 'glass', () => {
    pane.add(new THREE.PlaneGeometry(w, h), x, y, z - t / 2, 0, 0, 0)
    const F = 0.06
    for (const fz of [z - 0.03, z - t + 0.03]) {
      metal.box(w + F * 2, F, 0.06, x, y + h / 2 + F / 2, fz)
      metal.box(w + F * 2, F, 0.06, x, y - h / 2 - F / 2, fz)
      metal.box(F, h + F * 2, 0.06, x - w / 2 - F / 2, y, fz)
      metal.box(F, h + F * 2, 0.06, x + w / 2 + F / 2, y, fz)
    }
    metal.box(0.045, h, 0.05, x, y, z - t / 2)
    metal.box(w, 0.04, 0.05, x, y + h * 0.16, z - t / 2)
    // Отлив снаружи и подоконник изнутри. Снег на отливе — шейдерный.
    const OUT = 0.16
    dark.box(w + F * 2, 0.05, OUT, x, y - h / 2 - F, z + OUT / 2)
    dark.slab(x - w / 2 - F, x + w / 2 + F, z - t - 0.22, z - t, y - h / 2 - F, 0.05)
  })
}

/**
 * Обвязка фасада: кабельный лоток, трубы, вентрешётки, водосток, стремянка.
 *
 * Ровно то, чем настоящая станция отличается от коробки с окнами. На референсе
 * по стене служебного корпуса тянется лоток, от него уходят вниз гофры, между
 * окнами торчат решётки, а на крышу ведёт скоба-лестница. Ни одного нового
 * приёма: коробки и цилиндры, все — в `MAT.metalDark`.
 *
 * Всё висит на стене, смотрящей в −X, то есть на дорожку. Вылет держится в
 * пределах 0.35 м: дорожка — коридор, и вылезать на неё нельзя (`checkLayout`).
 */
function facadeGear(s: Spot, floor: number, rnd: () => number) {
  const x = s.x0
  const top = floor + s.h
  // Кабельный лоток под самой кромкой крыши, во всю длину секции.
  metal.box(0.22, 0.12, s.z1 - s.z0 - 0.6, x - 0.13, top - 0.55, (s.z0 + s.z1) / 2)
  for (let z = s.z0 + 1.2; z < s.z1 - 1; z += 2.6) {
    // Кронштейны лотка.
    metal.box(0.26, 0.05, 0.06, x - 0.13, top - 0.66, z)
  }
  // Гофрированные трубы вниз от лотка: цилиндр с «рёбрами» из шайб.
  for (const [z, len] of [
    [s.z0 + 2.4, s.h - 2.2],
    [s.z1 - 3.1, s.h - 3.4],
  ] as const) {
    if (len < 1) continue
    metal.pipe(0.075, len, x - 0.14, top - 0.62 - len, z, 7)
    for (let k = 0.15; k < len; k += 0.34) {
      metal.pipe(0.095, 0.05, x - 0.14, top - 0.62 - len + k, z, 7)
    }
  }
  // Водосточная труба по торцу секции, с отводом у земли.
  {
    const z = s.z0 + 0.55
    const len = s.h - 0.6
    metal.pipe(0.085, len, x - 0.16, floor + 0.35, z, 8)
    metal.strut(0.085, x - 0.16, floor + 0.42, z, x - 0.42, floor + 0.12, z)
    for (const y of [floor + 1.2, floor + 3.0]) metal.box(0.1, 0.06, 0.24, x - 0.16, y, z)
  }
  // Вентиляционные решётки между окнами: коробка с ламелями.
  for (let z = s.z0 + 4.3; z < s.z1 - 2; z += 6.8) {
    dark.box(0.12, 0.5, 0.62, x - 0.06, floor + 3.5, z)
    for (let k = 0; k < 4; k++) metal.box(0.14, 0.03, 0.56, x - 0.07, floor + 3.32 + k * 0.12, z)
  }
  // Скоба-лестница на крышу: две тетивы и перекладины. Ставится у дальнего
  // торца — так она не лезет в кадр поверх двери, но крышу объясняет.
  {
    const z = s.z1 - 1.2
    const y0 = floor + 1.1
    for (const dz of [-0.21, 0.21]) {
      metal.pipe(0.028, top + 0.75 - y0, x - 0.27, y0, z + dz, 5)
    }
    for (let y = y0; y < top + 0.5; y += 0.32) {
      metal.strut(0.02, x - 0.27, y, z - 0.21, x - 0.27, y, z + 0.21)
    }
    // Дуга безопасности у верха — характерная деталь всякой такой лестницы.
    for (let a = 0; a < 5; a++) {
      const t = a / 4
      metal.strut(
        0.018,
        x - 0.27,
        top - 0.3 + t * 0.5,
        z - 0.3,
        x - 0.27 - 0.25 * Math.sin(t * Math.PI),
        top - 0.3 + t * 0.5,
        z + 0.3,
      )
    }
  }
  // Щиток с номером над дверью — только на секции со входом.
  if (Math.abs(s.z0 - WING[P.entry.wing].z0) < 0.01) {
    dark.box(0.08, 0.34, 0.5, x - 0.04, floor + DOOR.h + 0.45, DOOR.z)
    metal.box(0.1, 0.03, 0.44, x - 0.05, floor + DOOR.h + 0.3, DOOR.z)
  }
  // Пара случайных скоб и кронштейнов: асимметрия важнее их формы.
  for (let k = 0; k < 3; k++) {
    const z = s.z0 + 1.5 + rnd() * (s.z1 - s.z0 - 3)
    metal.box(0.16, 0.08, 0.08, x - 0.08, floor + 1.4 + rnd() * 2.2, z)
  }
}

/**
 * Вертикальный подтёк по стене, смотрящей в -X.
 *
 * Самая дешёвая грязь из всех и самая заметная: чистая панельная стена
 * читается новостройкой, а станция стоит в мокром снегу десятилетиями.
 * Плоскость висит в двух с половиной сантиметрах от стены — заподлицо
 * поверхности спорят за глубину и идут полосами (урок сессии 11-бис).
 */
function streak(x: number, yBottom: number, z: number, w: number, h: number) {
  // `keepUV` — потому что альфа-карта натянута НА потёк целиком (`ClampToEdge`),
  // а не намощена: метрическая развёртка размазала бы её в одну полосу.
  grime.add(keepUV(new THREE.PlaneGeometry(w, h)), x - 0.025, yBottom + h / 2, z, 0, -Math.PI / 2, 0)
}

/** Сосульки под кромкой: конусы вниз, разной длины, с пропусками. */
function icicleRow(
  x: number,
  y: number,
  z0: number,
  z1: number,
  rnd: () => number,
  step = 0.42,
) {
  for (let z = Math.min(z0, z1) + 0.2; z < Math.max(z0, z1) - 0.2; z += step) {
    if (rnd() < 0.45) continue
    const len = 0.18 + rnd() * 0.5
    const r = 0.02 + rnd() * 0.025
    const geo = new THREE.ConeGeometry(r, len, 5)
    icicles.add(geo, x, y - len / 2, z + (rnd() - 0.5) * 0.15, Math.PI, 0, 0)
  }
}

/**
 * Окно в НАСТОЯЩЕМ проёме стены, смотрящей в −X: стекло одно на оба взгляда.
 *
 * Чем оно отличается от `windowXneg`. Там окно — две наклейки на глухой стене,
 * тёмная снаружи и светлая изнутри, и между ними бетон. Приём честно отработал
 * четыре фазы, пока внутрь нельзя было зайти; с интерьером он стал главной
 * ложью станции. Здесь стену режет `wall` (проём с подоконной частью), а сюда
 * приходит только заполнение проёма: стекло посередине толщины, рама с обеих
 * сторон, снаружи отлив со снегом, изнутри подоконник.
 *
 * Откосы рисовать не нужно: стена собрана из коробок, и торцы простенков —
 * это и есть откосы. Своя плита в той же плоскости дала бы полосы.
 *
 * `x` — наружная грань стены, `t` — её толщина, `y` — центр окна.
 */
function windowOpen(x: number, t: number, y: number, z: number, w: number, h: number) {
  piece('окно', 'glass', () => {
    // Стекло в середине проёма: рама с обеих сторон прикрывает его края,
    // а сам лист остаётся ровно один — он двусторонний (`MAT.pane`).
    pane.add(new THREE.PlaneGeometry(w, h), x + t / 2, y, z, 0, -Math.PI / 2, 0)
    const F = 0.06
    // Обвязка по периметру проёма с обеих сторон стены.
    for (const fx of [x + 0.03, x + t - 0.03]) {
      metal.box(0.06, F, w + F * 2, fx, y + h / 2 + F / 2, z)
      metal.box(0.06, F, w + F * 2, fx, y - h / 2 - F / 2, z)
      metal.box(0.06, h + F * 2, F, fx, y, z - w / 2 - F / 2)
      metal.box(0.06, h + F * 2, F, fx, y, z + w / 2 + F / 2)
    }
    // Переплёт: импост и планка. Стоят в плоскости стекла, а не у грани, —
    // иначе снаружи видно один переплёт, изнутри другой.
    metal.box(0.05, h, 0.045, x + t / 2, y, z)
    metal.box(0.05, 0.04, w, x + t / 2, y + h * 0.16, z)
    // Наружный отлив: толщину окну даёт выступ под ним. Снег на нём — слой.
    const OUT = 0.16
    dark.box(OUT, 0.05, w + F * 2, x - OUT / 2, y - h / 2 - F, z)
    // Подоконник изнутри.
    dark.slab(x + t, x + t + 0.22, z - w / 2 - F, z + w / 2 + F, y - h / 2 - F, 0.05)
  })
}

/**
 * Служебный корпус изнутри: коридор вдоль здания, комнаты по фасаду.
 *
 * До фазы 5 заходимой была одна дежурка, выписанная руками пятью слэбами.
 * Теперь секция строится по общей схеме, а числа планировки лежат в
 * `WING_PLAN` (layout.ts) — по тому же правилу, по которому там уже живут
 * пятна и дорожка: координаты объекта в одном месте.
 *
 * Правила, без которых внутрь не зайти, остались прежними:
 *   — проём 1.6 × 2.35: капсула игрока радиусом 0.34 проходит с запасом;
 *   — порог. Пол здания лежит на самой высокой точке пятна, а земля у двери
 *     ниже; без ступеньки снаружи вход становится стенкой в полметра
 *     (капсула переступает 0.3 м);
 *   — стены толщиной 0.35 идут В Octree вместе со всем `solid`, поэтому
 *     сквозь них не пройти, а сквозь проём — можно.
 *
 * И одно новое, вылезшее ровно на сквозном коридоре: **полы секций разные**
 * (1.85, 0.25, −1.15 — корпус стоит ступеньками по гребню). Проём между
 * секциями поэтому идёт от отметки ВЕРХНЕЙ, а спуск собирает внутренний марш
 * сразу за ним. Потолок над этим маршем приходится поднимать: при обычных
 * 3.1 м перемычка проёма оказывается выше потолка нижней секции, и проход
 * упирается в перекрытие.
 */
const P = WING_PLAN
/** Дверь на улицу: числа нужны и стене, и ореолу снаружи. */
const DOOR = { z: P.entry.z, w: P.door.w, h: P.door.h }

/** Комнаты секции по фасаду, из планировки. */
const roomsOf = (i: number) => P.rooms.filter((r) => r.wing === i)

/**
 * Окна секции с пометкой «настоящий проём».
 *
 * Проём режется только там, где за стеной комната: в простенке между
 * комнатами или за монолитной частью секции он выходил бы в толщу бетона.
 * Считается это в одном месте, потому что ответ нужен двоим — стене
 * (`wingSection` кладёт `Hole`) и заполнению (`buildBuildings` ставит стекло).
 */
function wingWins(i: number) {
  const rooms = roomsOf(i)
  return wingWindows(i).map((w) => ({
    ...w,
    open: rooms.some((r) => w.z > r.z0 + 0.9 && w.z < r.z1 - 0.9),
  }))
}

/** Пол секции корпуса. Считается дважды — здесь и в `buildBuildings` — по одной формуле. */
const wingFloor = (i: number) => floorOf(WING[i])

/**
 * Дверной косяк и порог наружу. Вынесено из тела секции: то же самое понадобилось
 * центральному корпусу и вестибюлю купола.
 */
function doorway(x: number, xIn: number, z: number, w: number, h: number, floor: number) {
  piece('проём', 'door', () => doorFrame(x, xIn, z, w, h, floor))
}

function doorFrame(x: number, xIn: number, z: number, w: number, h: number, floor: number) {
  const F = 0.12
  // Косяк ЗАХОДИТ в проём на `OVER`, а не прикладывается к нему заподлицо.
  // Заподлицо его боковина ложится в ту же плоскость, что откос простенка,
  // обе смотрят внутрь проёма — и глубинный буфер выбирает между ними по
  // пикселям: в кадре косяк идёт полосами. Полтора сантиметра нахлёста
  // убирают спор и в проёме незаметны.
  const OVER = 0.015
  dark.slab(x - F, xIn + F, z - w / 2 - F, z - w / 2 + OVER, floor, h + F)
  dark.slab(x - F, xIn + F, z + w / 2 - OVER, z + w / 2 + F, floor, h + F)
  dark.slab(x - F, xIn + F, z - w / 2 - F, z + w / 2 + F, floor + h - OVER, F)
}

/** Ступеньки от порога до земли. Число ступеней — по фактическому перепаду. */
function threshold(x: number, z: number, floor: number, ground: number, halfW = 1.1) {
  const rise = floor - ground
  if (rise <= 0.05) return
  const steps = Math.max(1, Math.ceil(rise / 0.24))
  for (let i = 0; i < steps; i++) {
    const y = ground + (rise * i) / steps
    dark.slab(x - 0.35 - (steps - i) * 0.34, x, z - halfW, z + halfW, y - 0.1, rise / steps + 0.1)
  }
}

/**
 * Крыльцо у двери, смотрящей в +Z: марш ступеней ВМЕСТЕ с плитой, на которой
 * он стоит. Двум дверям комплекса на полке — центрального корпуса и вестибюля
 * обсерватории.
 *
 * Плита — не украшение. Комплекс поднят на собственный уступ (`SHELF_LIFT`),
 * перепад от порога до земли под три метра, а марш растёт вглубь
 * пропорционально перепаду: носок нижней ступени оказывается в 4–9 м от стены.
 * Ровная часть полки кончается на z ≈ −49.3, двери стоят на −52.1 и −49.6 —
 * то есть нижние ступени обеих лестниц висели над скатом, держась на честном
 * слове, а сойти с них было некуда. Землю там не насыпать (плоское плато
 * съедает полкадра — отвергнуто ещё в фазе 3.5), поэтому опору даёт бетон:
 * плита от порога до площадки перед маршем, а под ней подпорная стенка
 * до самого грунта.
 *
 * Целятся марши не в грунт, а в отметку входной площадки (`ground`): обе двери
 * выходят на одну плиту, и мерить каждую по своей пробе рельефа значило бы
 * получить два крыльца на разных уровнях в двух метрах друг от друга.
 * Собственная опора кладётся только до `zStop` — дальше начинается сама
 * площадка, и вторая плита поверх неё дала бы копланарные грани.
 */
function porch(x: number, zEdge: number, floor: number, ground: number, zStop: number, halfW = 1.1) {
  const SIDE = 0.7 // плита шире марша — иначе с неё сходишь мимо
  const rise = floor - ground
  if (rise <= 0.05) return
  const steps = Math.max(1, Math.ceil(rise / 0.24))

  // Подпорная стенка под той частью марша, что висит перед площадкой.
  if (zStop > zEdge + 0.05) {
    const base = lowestIn(x - halfW - SIDE, x + halfW + SIDE, zEdge, zStop)
    dark.slab(x - halfW - SIDE, x + halfW + SIDE, zEdge, zStop, base - 0.4, ground - base + 0.4)
  }

  for (let i = 0; i < steps; i++) {
    const y = ground + (rise * i) / steps
    dark.slab(x - halfW, x + halfW, zEdge, zEdge + 0.35 + (steps - i) * 0.34, y - 0.1, rise / steps + 0.1)
  }
}

/**
 * То же крыльцо, но марш идёт ВДОЛЬ фасада, а не от него.
 *
 * Нужно там, где перепад не помещается в глубину площадки. У вестибюля
 * обсерватории пол выше плиты на 3.1 м — это четырнадцать ступеней, пять
 * метров выноса, а от стены до кромки площадки всего три: прямой марш
 * повисал последними ступенями над обрывом, и его же поперёк резали перила
 * ограждения. Вдоль стены места вдоволь — пятно купола тянется до x −22.
 *
 * Опора кладётся только до `xStop`: дальше начинается сама площадка, и вторая
 * плита поверх неё дала бы копланарные грани.
 */
function porchSide(
  x: number,
  zEdge: number,
  floor: number,
  ground: number,
  dir: -1 | 1,
  xStop: number,
  halfW = 1.1,
  // Марш стоит поперёк площадки, а та всего 3 м глубиной: при ширине 2.2
  // вдоль неё оставалась полоса в 0.9 м, и мимо лестницы было не пройти —
  // то есть к её собственному низу было не подойти.
  depth = 1.7,
) {
  const rise = floor - ground
  if (rise <= 0.05) return
  const steps = Math.max(1, Math.ceil(rise / 0.24))
  const RUN = 0.34
  const z1 = zEdge + depth

  // Площадка у порога на уровне пола: из двери выходят прямо, поворачивают уже на ней.
  dark.slab(x - halfW, x + halfW, zEdge, z1, floor - 0.45, 0.45)

  const xa = x + dir * halfW
  const xEnd = xa + dir * steps * RUN
  // Опора — только там, где марш вышел ЗА чужую плиту. Внутри неё своя вторая
  // плита на той же отметке дала бы копланарные грани, то есть полосы.
  const out = dir < 0 ? xEnd < xStop : xEnd > xStop
  if (out) {
    const base = lowestIn(Math.min(xEnd, xStop), Math.max(xEnd, xStop), zEdge, z1)
    dark.slab(Math.min(xEnd, xStop), Math.max(xEnd, xStop), zEdge, z1, base - 0.4, ground - base + 0.4)
  }

  for (let i = 0; i < steps; i++) {
    const y = ground + (rise * i) / steps
    const xb = xa + dir * (steps - i) * RUN
    dark.slab(Math.min(xa, xb), Math.max(xa, xb), zEdge, z1, y - 0.1, rise / steps + 0.1)
  }
}

/**
 * Секция служебного корпуса: наружные стены с проёмами, коридор, комнаты.
 * Возвращать ничего не нужно — всё копится в общих `Parts` и в реестре комнат.
 */
function wingSection(i: number, inter: Interiors, group: THREE.Group, warm: Warm[]) {
  const s = WING[i]
  const floor = wingFloor(i)
  const T = P.wallT
  const H = P.roomH
  // За коридором секция снова монолит, и монолит начинается РОВНО на границе
  // коридора: сам массив бетона и есть его правая стена, отдельной перегородки
  // тут нет. С прибавкой в толщину стены (`+ T`) между стеной и планировкой
  // оставалась ниша в 35 см на всю длину корпуса — не видная как ниша, но
  // видная тремя своими следствиями: полоса пола вдоль стены не попадала
  // в зарегистрированный объём (на ней лежал уличный снег и в неё падали
  // хлопья), а труба, щиток и объявления, поставленные по планировке,
  // висели в воздухе, не доставая до стены.
  const back = P.corr.x1
  const rooms = roomsOf(i)
  // Марш этой секции считается заранее: от него зависит не только потолок,
  // но и ВЫСОТА поперечной стены с проёмом. Проём начинается на отметке пола
  // соседней (верхней) секции, и в стене высотой 3.1 от СВОЕГО пола он
  // обрезается сверху до 1.7 м — игрок упирается в перемычку, хотя в плане
  // всё сходится. Ровно это и вылезло на первом автопроходе.
  const zone = stairZoneOf(i, floor)

  roofCap(s.x0, s.x1, s.z0, s.z1, floor + s.h)
  walls.slab(back, s.x1, s.z0, s.z1, floor, s.h) // глухая половина секции
  // Отдельной плиты пола НЕТ, и это не экономия: её верх лежал ровно на `floor`,
  // где кончается цоколь (`plinth`), — две грани в одной плоскости смотрят
  // вверх, и глубинный буфер выбирает между ними по пикселям. В кадре это
  // полосы поперёк пола. Полом служит верх цоколя.

  // --- Наружная стена по фасаду ---------------------------------------------
  // Окна режутся в стене, а не наклеиваются на неё: только так изнутри видно
  // улицу, а снаружи — что в комнате горит свет.
  const facade: Hole[] = i === P.entry.wing ? [{ at: DOOR.z, w: DOOR.w, h: DOOR.h }] : []
  for (const w of wingWins(i)) {
    if (w.open) facade.push({ at: w.z, w: WING_WIN.w, h: WING_WIN.h, sill: WING_WIN.mid - WING_WIN.h / 2 })
  }
  wall(walls, { axis: 'z', from: s.z0, to: s.z1, at: s.x0, t: T, y: floor, h: H, holes: facade })
  if (i === P.entry.wing) {
    doorway(s.x0, s.x0 + T, DOOR.z, DOOR.w, DOOR.h, floor)
    threshold(s.x0, DOOR.z, floor, heightAt(s.x0 - 1.1, DOOR.z))
    // Створка, откинутая к стене: дверь открыта, и это видно.
    metal.slab(s.x0 - 0.08, s.x0, DOOR.z + DOOR.w / 2, DOOR.z + DOOR.w / 2 + 1.5, floor + 0.05, DOOR.h - 0.1)
  }

  // --- Поперечные стены: у соседней секции пол другой, проём идёт от её отметки
  const linkAt = (z: number) => P.links.find((l) => Math.abs(l.z - z) < 0.01)
  for (const [z, at] of [
    [s.z0, s.z0],
    [s.z1, s.z1 - T],
  ] as const) {
    const link = linkAt(z)
    const holes: Hole[] = []
    let hWall = H
    if (link) {
      // Отметка пола соседней секции: проём общий на двоих, и его низ берётся
      // по ВЫСШЕМУ из полов — иначе половина проёма уходит в перекрытие.
      const other = WING.findIndex((w, k) => k !== i && (Math.abs(w.z0 - z) < 0.01 || Math.abs(w.z1 - z) < 0.01))
      const sill = other >= 0 ? Math.max(0, wingFloor(other) - floor) : 0
      holes.push({ at: link.x, w: P.door.w, h: P.door.h, sill })
      // Стена у марша идёт до поднятого потолка: иначе проём срезан перемычкой.
      if (sill > 0 && zone) hWall = zone.ceil - floor
    }
    wall(walls, { axis: 'x', from: s.x0, to: back, at, t: T, y: floor, h: hWall, holes })
    // Кусок стены над проёмом до обычного потолка, если стена оказалась выше.
    if (hWall > H + 0.01) walls.slab(s.x0, P.corr.x0 - T, at, at + T, floor + H, hWall - H)
  }

  // --- Перегородка коридора с дверями в комнаты ------------------------------
  wall(walls, {
    axis: 'z',
    from: s.z0,
    to: s.z1,
    at: P.corr.x0 - T,
    t: T,
    y: floor,
    h: H,
    holes: rooms.map((r) => ({ at: r.door, w: P.door.w, h: P.door.h })),
  })
  for (const r of rooms) doorway(P.corr.x0 - T, P.corr.x0, r.door, P.door.w, P.door.h, floor)

  // --- Перегородки между соседними комнатами секции --------------------------
  for (let k = 1; k < rooms.length; k++) {
    const a = rooms[k - 1]
    const b = rooms[k]
    const lo = Math.min(a.z0, b.z0) === a.z0 ? a : b
    const hi = lo === a ? b : a
    walls.slab(s.x0, P.corr.x0 - T, lo.z1, hi.z0, floor, H)
  }

  // --- Потолок. Над маршем он выше: иначе проём в соседнюю секцию упрётся -----
  if (zone) {
    walls.slab(s.x0, back, s.z0, zone.zA, floor + H, s.h - H)
    walls.slab(s.x0, back, zone.zB, s.z1, floor + H, s.h - H)
    walls.slab(s.x0, P.corr.x0 - T, zone.zA, zone.zB, floor + H, s.h - H) // над комнатами обычный
    walls.slab(P.corr.x0 - T, back, zone.zA, zone.zB, zone.ceil, floor + s.h - zone.ceil)
    // Сам марш: собирает разницу полов соседних секций.
    piece('марш', 'stair', () =>
      flight(walls, {
        axis: 'z',
        w0: P.corr.x0,
        w1: P.corr.x1,
        start: zone.start,
        sign: zone.sign,
        yTop: zone.yTop,
        yBottom: floor,
      }),
    )
  } else {
    walls.slab(s.x0, back, s.z0, s.z1, floor + H, s.h - H)
  }

  // --- Реестр объёмов --------------------------------------------------------
  inter.add({
    name: `коридор ${i}`,
    x0: P.corr.x0,
    x1: P.corr.x1,
    z0: s.z0 + T,
    z1: s.z1 - T,
    y0: floor - 0.5,
    y1: floor + s.h,
  })
  for (const r of rooms) {
    inter.add({
      name: r.name,
      x0: s.x0 + T,
      x1: P.corr.x0 - T,
      z0: r.z0,
      z1: r.z1,
      y0: floor - 0.5,
      y1: floor + H,
    })
  }

  // --- Обстановка ------------------------------------------------------------
  for (const r of rooms) {
    furnishRoom(
      KIT,
      {
        name: r.name,
        x0: s.x0 + T,
        x1: P.corr.x0 - T,
        z0: r.z0,
        z1: r.z1,
        floor,
        h: H,
        door: r.door,
        doorW: P.door.w,
      },
      group,
      warm,
    )
  }
  furnishCorridor(
    KIT,
    { i, x0: P.corr.x0, x1: P.corr.x1, z0: s.z0 + T, z1: s.z1 - T, floor, h: H },
    group,
  )
}


/**
 * Внутренний марш этой секции, если он ей достался.
 *
 * Марш всегда стоит в НИЖНЕЙ секции пары и идёт от стены вглубь: подниматься
 * ему некуда, а в верхней секции пришлось бы резать нишу в цоколе.
 * `ceil` — отметка потолка над маршем; он выше обычного, потому что проём
 * начинается на уровне пола верхней секции.
 */
type StairZone = { zA: number; zB: number; ceil: number; start: number; sign: 1 | -1; yTop: number }

function stairZoneOf(i: number, floor: number): StairZone | null {
  const s = WING[i]
  for (const l of P.links) {
    const atZ1 = Math.abs(s.z1 - l.z) < 0.01
    const atZ0 = Math.abs(s.z0 - l.z) < 0.01
    if (!atZ1 && !atZ0) continue
    const upper = WING.findIndex(
      (w, k) => k !== i && (Math.abs(w.z0 - l.z) < 0.01 || Math.abs(w.z1 - l.z) < 0.01),
    )
    if (upper < 0) continue
    const yTop = wingFloor(upper)
    if (yTop <= floor + 0.05) continue // эта секция выше — марш строит соседняя

    const sign: 1 | -1 = atZ1 ? -1 : 1
    const start = atZ1 ? l.z - P.wallT : l.z + P.wallT
    const len = Math.ceil((yTop - floor) / 0.2) * 0.32 + 0.6
    const end = start + sign * len
    // Потолок над маршем: перемычка проёма плюс запас, но не выше крыши секции.
    const ceil = Math.min(yTop + P.door.h + 0.2, floor + s.h - 0.2)
    // Зона включает саму стену с проёмом (`l.z`, а не внутреннюю грань):
    // иначе обычный потолок ложится ровно поперёк проёма и режет его до 1.7 м.
    return { zA: Math.min(l.z, end), zB: Math.max(l.z, end), ceil, start, sign, yTop }
  }
  return null
}

export function buildBuildings(): {
  group: THREE.Group
  warm: Warm[]
  spill: Warm[]
  /** Заходимые объёмы: по ним снег знает про крышу, а звук — про стену. */
  interiors: Interiors
} {
  const group = new THREE.Group()
  group.name = 'buildings'
  const warm: Warm[] = []
  const spill: Warm[] = []
  const interiors = new Interiors()
  // Детерминированный: рисунок сосулек и грязи не должен плясать от перезагрузки.
  const rand = rng(51219)

  // Отметка входной площадки. Та же, что у верхней ступени марша, — плиту
  // кладёт `props.ts` по этому же числу. Сюда оно нужно крыльцам комплекса:
  // они сходят НА площадку, а не на грунт под ней.
  const APRON_TOP = stairProfile().topY

  // --- Служебный корпус справа ---------------------------------------------
  // Секции 0..2 заходимы (коридор + комнаты по фасаду), дальняя третья осталась
  // монолитом: её пол на 4.1 м выше соседней, и коридор упёрся бы в лестницу
  // длиннее самой секции. В кадре она — дальний торец в тумане.
  for (let i = 0; i < WING.length; i++) {
    const s = WING[i]
    const floor = floorOf(s)
    plinth(s.x0, s.x1, s.z0, s.z1, floor)
    const open = roomsOf(i).length > 0
    if (open) wingSection(i, interiors, group, warm)
    else shell(s.x0, s.x1, s.z0, s.z1, floor, s.h)

    // Лента окон по стене, смотрящей на дорожку.
    //
    // Там, где за стеной комната, окно — настоящий проём со стеклом: свет из
    // комнаты выходит наружу сам, и «горящее окно» больше не рисуется краской.
    // Где комнаты нет (дальняя монолитная секция, простенок) — прежняя
    // накладка трёх сортов: тёмное, светлое тёмное, горящее.
    for (const { z, n, open: cut } of wingWins(i)) {
      if (cut) {
        windowOpen(s.x0, P.wallT, floor + WING_WIN.mid, z, WING_WIN.w, WING_WIN.h)
      } else {
        const kind: 0 | 1 | 2 = n % 3 === 1 ? 1 : 0
        windowXneg(s.x0, floor + WING_WIN.mid, z, WING_WIN.w, WING_WIN.h, kind)
      }
      // Потёк от отлива вниз по стене — там, где с окна годами течёт талая вода.
      streak(s.x0, floor + WING_WIN.mid - 0.65 - 1.15, z + (n % 2 ? 0.5 : -0.45), 0.34, 1.15)
    }
    // Брызги у цоколя по всей длине фасада: нижние полметра стены на референсе
    // всегда темнее — их бьёт снегом с земли.
    {
      // Альфа-карта грязи плотная СВЕРХУ (она рисовалась под потёк от окна),
      // а брызги у земли устроены наоборот. Переворачивается UV самой
      // геометрии, а не плоскость поворотом: `Parts.add` собирает Эйлера XYZ,
      // и разворот вокруг нормали у уже повёрнутой по рысканью плоскости
      // уехал бы вокруг мировой оси (то же правило, что у наклонов).
      const g = new THREE.PlaneGeometry(s.z1 - s.z0 - 0.4, 0.9)
      const uv = g.attributes.uv as THREE.BufferAttribute
      for (let k = 0; k < uv.count; k++) uv.setY(k, 1 - uv.getY(k))
      grime.add(keepUV(g), s.x0 - 0.025, floor + 0.5, (s.z0 + s.z1) / 2, 0, -Math.PI / 2, 0)
    }
    // Сосульки по кромке крыши фасада. Свисают с парапета, то есть с самой
    // верхней грани — с той, что рисует силуэт здания на фоне тумана.
    icicleRow(s.x0 - 0.04, floor + s.h + 0.62, s.z0, s.z1, rand)
    facadeGear(s, floor, rand)
  }

  // --- Открытая дверь: главное тёплое пятно кадра ---------------------------
  // На референсе это оранжевый прямоугольник с отражением на мокром бетоне.
  //
  // Фаза 5: сама светящаяся плоскость в проёме убрана. До интерьера дверь была
  // нарисованной — эмиссивный прямоугольник поверх глухой стены; теперь за ней
  // настоящая комната со своей лампой, и оранжевый прямоугольник в кадре
  // получается сам собой. Ореол и отсвет на бетоне остались: их даёт не
  // геометрия, а `glow.ts`, и считать их по свету из комнаты незачем.
  {
    const s = WING[1]
    const floor = floorOf(s)
    const z = DOOR.z
    warm.push({
      pos: new THREE.Vector3(s.x0 - 0.9, floor + 1.2, z),
      color: 0xff7a2a,
      // 5.5 м давало над дверью оранжевый овал в полстены: свет в тумане
      // виден недалеко, растёт не ореол, а его яркость.
      size: 3.0,
      // 1.0 — это было зарево жилого дома. Теперь за дверью только печь
      // в дежурке через коридор: света хватает на проём и на пятно у порога.
      power: 0.5,
      label: 'дверь',
    })
    // Отсвет на мокром бетоне перед дверью — самая заметная деталь референса.
    // Тянется от порога наружу, поэтому центр сдвинут и растянут по X.
    spill.push({
      pos: new THREE.Vector3(s.x0 - 3.2, heightAt(s.x0 - 3.2, z) + 0.12, z),
      color: 0xff7a2a,
      size: 3.2,
      power: 0.24,
      stretch: 1.9,
      label: 'отсвет двери',
    })
    // Одно тёплое окно в тёмном фасаде — то самое окно дежурки, за которым
    // топится печь. Точечный источник внутри комнаты улицу не осветит (GI
    // в сцене нет), поэтому свет «наружу» рисует ореол, как у двери. Окно
    // выбрано ближайшее к печи: она стоит у дальней стены комнаты.
    // Координаты берутся у самих окон (`wingWindows`), а не назначаются: первая
    // версия встала на z −1.4, где окна нет вовсе — у секции со входом их два,
    // на −11.6 и −8.2 (третье съедено дверным проёмом). Ореол висел на глухой
    // стене, и это было видно только в кадре у порога.
    const duty = wingWindows(1).map((w) => w.z).find((wz) => wz > -9.4 && wz < -0.85)
    if (duty !== undefined) {
      warm.push({
        pos: new THREE.Vector3(s.x0 - 0.15, floor + WING_WIN.mid, duty),
        color: 0xff9a4a,
        size: 1.3,
        // Слабее двери: печь стоит у противоположной стены комнаты, до окна
        // достаёт только зарево.
        power: 0.22,
        label: 'окно дежурки',
      })
    }
  }

  // --- Настенные фонари: погасли ---------------------------------------------
  // До фазы 12 их было два, и они держали правый борт кадра. На брошенной
  // станции фонарь горит только если есть кому его чинить: плафоны остались
  // тёмными коробками, подтёки под кронштейнами и сосульки — на месте
  // (они и рассказывают, что тут когда-то было тепло).
  for (const [wing, z] of [
    [0, 8],
    [2, -19],
  ] as const) {
    const s = WING[wing]
    const floor = floorOf(s)
    const y = floor + s.h - 1.1
    metal.box(0.5, 0.14, 0.14, s.x0 - 0.25, y + 0.3, z) // кронштейн
    dark.box(0.42, 0.3, 0.46, s.x0 - 0.5, y, z)
    streak(s.x0, floor + 0.5, z, 0.22, s.h - 1.7)
    icicleRow(s.x0 - 0.5, y - 0.15, z - 0.22, z + 0.22, rand, 0.16)
  }

  // --- Центральный корпус с освещёнными окнами ------------------------------
  // Средний план референса: светлая коробка с лентой окон ВПЛОТНУЮ к куполу.
  //
  // До фазы 3.5 корпус стоял в седловине гребня (земля -3.8 против +9.7 под
  // куполом) и сидел прямо поперёк дорожки. В кадре это читалось как стена,
  // перегородившая проход: коридор упирался в здание, а купол уезжал за него.
  // Теперь корпус на полке, справа от купола, торцом с окнами к игроку.
  {
    const { x0, x1, z0, z1, h } = CORE
    const floor = floorOf(CORE)
    const R = CORE_ROOM
    const T = R.wallT
    plinth(x0, x1, z0, z1, floor)
    roofCap(x0, x1, z0, z1, floor + h)
    // Второй объём поверх первого: на референсе у среднего корпуса ступенчатая
    // крыша. Раньше он ставился рядом, вглубь по Z, — на полке места нет,
    // и такой объём висел бы над обрывом.
    shell(x0 + 2.5, x1 - 2.5, z0 + 3, z1 - 2, floor + h, 3.2)

    // --- Операторская: корпус полый, стены идут по периметру пятна -----------
    // пола отдельной плитой нет — им служит верх цоколя, см. `wingSection`
    walls.slab(x0, x1, z0, z1, floor + R.h, h - R.h) // потолок и чердак
    wall(walls, { axis: 'x', from: x0, to: x1, at: z0, t: T, y: floor, h: R.h })
    wall(walls, { axis: 'z', from: z0, to: z1, at: x0, t: T, y: floor, h: R.h })
    wall(walls, { axis: 'z', from: z0, to: z1, at: x1 - T, t: T, y: floor, h: R.h })
    // Торец к игроку: в нём и лента окон, и единственная дверь. Окна — проёмы,
    // поэтому свет операторской, который виден с дорожки, тот же самый, что
    // горит внутри: раньше это были два независимых прямоугольника.
    wall(walls, {
      axis: 'x',
      from: x0,
      to: x1,
      at: z1 - T,
      t: T,
      y: floor,
      h: R.h,
      holes: [
        { at: R.door.x, w: R.door.w, h: R.door.h },
        ...coreWindows().map((x) => ({
          at: x,
          w: R.win.w,
          h: R.win.h,
          sill: R.sill - R.win.h / 2,
        })),
      ],
    })
    // Косяк и порог: земля у торца ниже пола на треть метра.
    {
      const F = 0.12
      const O = 0.015 // нахлёст в проём: заподлицо косяк спорит со стеной за глубину
      const d = R.door
      piece('проём', 'door', () => {
        dark.slab(d.x - d.w / 2 - F, d.x - d.w / 2 + O, z1 - T - F, z1 + F, floor, d.h + F)
        dark.slab(d.x + d.w / 2 - O, d.x + d.w / 2 + F, z1 - T - F, z1 + F, floor, d.h + F)
        dark.slab(d.x - d.w / 2 - F, d.x + d.w / 2 + F, z1 - T - F, z1 + F, floor + d.h - O, F)
      })
      porch(d.x, z1, floor, APRON_TOP, APRON.z0)
    }
    interiors.add({
      name: 'операторская',
      x0: x0 + T,
      x1: x1 - T,
      z0: z0 + T,
      z1: z1 - T,
      y0: floor - 0.5,
      y1: floor + R.h,
    })

    // лента окон на торце, обращённом к игроку
    for (const x of coreWindows()) windowOpenZ(z1, T, floor + R.sill, x, R.win.w, R.win.h)

    // --- Обстановка операторской (furnish.ts) --------------------------------
    furnishCore(
      KIT,
      { x0, x1, z0, z1, floor, h: R.h, wallT: T, winFrom: R.winFrom },
      group,
    )

    // Свет за лентой окон погашен (фаза 12). Раньше здесь стоял источник
    // снаружи (12 Вт на 34 м) и размытое пятно на всю ленту — вместе они
    // делали корпус вторым тёплым акцентом кадра. Теперь лента читается
    // рядом тёмных проёмов: на дальнем плане это единственное, что отличает
    // брошенный корпус от жилого.
  }

  // --- Купол обсерватории ---------------------------------------------------
  // Дальний план: цилиндр + полусфера, щель — тёмная коробка поверх.
  // Радиус 6.3 → 7.0: с прежним купол читался вдвое мельче референсного.
  {
    const { x, z, r: R, drumH } = DOME
    const B = DOME_BASE
    const floor = floorOf(B)
    const T = DOME_ROOM.wallT
    const drumY = floor + B.h
    plinth(B.x0, B.x1, B.z0, B.z1, floor)
    // Парапет без снежной шапки: `roofCap` кладёт снег по всему пятну, а здесь
    // отметка крыши цоколя — это ПОЛ ЗАЛА и проём лестницы. Шапка легла поверх
    // проёма и остановила подъём на середине марша, упершись игроку в макушку;
    // заодно она была бы полом зала — снег внутри обсерватории.
    {
      const Pr = 0.32
      dark.slab(B.x0, B.x1, B.z0, B.z0 + Pr, drumY, 0.55)
      dark.slab(B.x0, B.x1, B.z1 - Pr, B.z1, drumY, 0.55)
      dark.slab(B.x0, B.x0 + Pr, B.z0, B.z1, drumY, 0.55)
      dark.slab(B.x1 - Pr, B.x1, B.z0, B.z1, drumY, 0.55)
    }

    // --- Вестибюль в цоколе и марш в зал --------------------------------------
    // Перепад 5.3 м — 27 ступеней вдоль левой стены.
    //
    // Направление марша выбрано не из удобства: **верх обязан выйти ВНУТРИ
    // барабана**. Первый заход поднимал игрока в дальний угол цоколя (радиус
    // 7.93 при внутреннем радиусе барабана 7.9) — то есть ровно в стену зала:
    // подъём вставал на середине, а спуск сверху работал. Теперь марш идёт
    // от дальней стены ВВЕРХ к центру, и выход лежит в 7.0 м от оси купола.
    const sx0 = B.x0 + DOME_ROOM.stairX
    const sx1 = sx0 + DOME_ROOM.stairWidth
    const ceilY = drumY - 0.3
    const zTop = B.z1 - 7.1 // площадка выхода в зал
    piece('марш в зал', 'stair', () =>
      flight(walls, {
        axis: 'z',
        w0: sx0,
        w1: sx1,
        start: zTop,
        sign: -1,
        yTop: drumY,
        yBottom: floor,
      }),
    )

    // Проём в перекрытии — над ВЕРХНЕЙ частью марша: ниже по маршу высоты
    // до перекрытия хватает, и дыру там держать незачем.
    const zHole = zTop - 5.0
    // пол вестибюля — верх цоколя, см. `wingSection`
    walls.slab(B.x0, sx0, B.z0, B.z1, ceilY, 0.3) // перекрытие левее марша
    walls.slab(sx1, B.x1, B.z0, B.z1, ceilY, 0.3) // и правее
    walls.slab(sx0, sx1, B.z0, zHole, ceilY, 0.3) // за дальним концом проёма
    walls.slab(sx0, sx1, zTop + 0.5, B.z1, ceilY, 0.3) // и перед площадкой выхода
    // Ограждение проёма: без него с площадки зала шагаешь прямо в пустоту.
    piece('ограждение проёма', 'furn', () => {
      for (let zz = zHole; zz < zTop + 0.5; zz += 1.4) metal.pipe(0.05, 1.05, sx1, drumY, zz, 5)
      metal.strut(0.045, sx1, drumY + 1.05, zHole, sx1, drumY + 1.05, zTop + 0.5)
    })

    const dz = B.z1
    const dr = DOME_ROOM.door
    wall(walls, { axis: 'x', from: B.x0, to: B.x1, at: B.z0, t: T, y: floor, h: B.h - 0.3 })
    wall(walls, { axis: 'z', from: B.z0, to: B.z1, at: B.x0, t: T, y: floor, h: B.h - 0.3 })
    wall(walls, { axis: 'z', from: B.z0, to: B.z1, at: B.x1 - T, t: T, y: floor, h: B.h - 0.3 })
    wall(walls, {
      axis: 'x',
      from: B.x0,
      to: B.x1,
      at: dz - T,
      t: T,
      y: floor,
      h: B.h - 0.3,
      holes: [{ at: dr.x, w: dr.w, h: dr.h }],
    })
    {
      const F = 0.12
      const O = 0.015 // нахлёст в проём, см. `doorway`
      piece('проём', 'door', () => {
        dark.slab(dr.x - dr.w / 2 - F, dr.x - dr.w / 2 + O, dz - T - F, dz + F, floor, dr.h + F)
        dark.slab(dr.x + dr.w / 2 - O, dr.x + dr.w / 2 + F, dz - T - F, dz + F, floor, dr.h + F)
        dark.slab(dr.x - dr.w / 2 - F, dr.x + dr.w / 2 + F, dz - T - F, dz + F, floor + dr.h - O, F)
      })
      porchSide(dr.x, dz, floor, APRON_TOP, -1, APRON.x0)
    }
    interiors.add({
      name: 'вестибюль обсерватории',
      x0: B.x0 + T,
      x1: B.x1 - T,
      z0: B.z0 + T,
      z1: B.z1 - T,
      y0: floor - 0.5,
      y1: drumY,
    })
    // Тамбур: сюда входят с мороза, здесь раздеваются (furnish.ts). До фазы 8
    // самое большое помещение станции было пустым на 91 % площади.
    furnishLobby(
      KIT,
      {
        x0: B.x0 + T,
        x1: B.x1 - T,
        z0: B.z0 + T,
        z1: B.z1 - T,
        floor,
        doorX: dr.x,
        stairX: sx0,
      },
      group,
    )
    // Зал круглый, и с фазы 9 он регистрируется именно так: рамка — описанный
    // квадрат, стена — круг внутреннего радиуса барабана. До этого он был
    // вписан в квадрат 0.85 от радиуса, то есть рамка была УЖЕ стены по осям
    // (7.57 против 8.6 — мебель у стены считалась ушедшей в неё) и ШИРЕ
    // по диагоналям (10.7 — в углах за барабаном не шёл снег).
    interiors.add({
      name: 'зал обсерватории',
      x0: x - (R - 0.3),
      x1: x + (R - 0.3),
      z0: z - (R - 0.3),
      z1: z + (R - 0.3),
      r: R - 0.3,
      // Объём регистрируется РОВНО на 0.5 ниже пола: это соглашение, по
      // которому `npm run room` находит отметку пола (`room.y0 + 0.5`).
      // При 0.4 инструмент считал пол на 10 см выше настоящего, и вся
      // обстановка зала показывалась «уходящей под пол на 0.10 м».
      y0: drumY - 0.5,
      y1: drumY + drumH + R * 0.6,
    })

    // Свет вестибюля и зала — теперь не «дежурный», а просто улица, попавшая
    // внутрь: в вестибюль через открытую дверь и окна, в зал — через щель
    // купола, которую некому закрыть. Поэтому источники приглушены (6 → 4
    // и 7 → 5) и оба ушли в цвет неба: тёплого света в обсерватории нет.
    const hall = new THREE.PointLight(0x9fc2da, 4, 15, 2)
    hall.position.set(sx1 + 1.5, floor + 2.6, (B.z0 + B.z1) / 2)
    group.add(hall)
    const upper = new THREE.PointLight(0x9fc2da, 5, 20, 2)
    upper.position.set(x, drumY + 2.4, z)
    group.add(upper)

    // --- Зал изнутри: стены барабана, купол и телескоп -------------------------
    // Изнанка строится отдельной геометрией с вывернутыми гранями: одна
    // поверхность не может быть видна с двух сторон разными материалами,
    // а `side: DoubleSide` на всём мире стоил бы вдвое больше пикселей.
    const inner = (geo: THREE.BufferGeometry) => {
      geo.scale(-1, 1, 1) // отражение переворачивает обход граней
      geo.computeVertexNormals() // и нормали пересчитываются внутрь
      return geo
    }
    walls.add(inner(new THREE.CylinderGeometry(R - 0.3, R - 0.3, drumH, 28, 1, true)), x, drumY + drumH / 2, z)
    walls.add(
      inner(new THREE.SphereGeometry(R - 0.3, 30, 16, 0, Math.PI * 2, 0, Math.PI / 2)),
      x,
      drumY + drumH,
      z,
    )

    // Телескоп: тумба, вилка, труба. Наклон трубы запечён в геометрию —
    // через `rx` в `Parts.add` он уехал бы вокруг мировой оси (правило фазы 4).
    piece('телескоп', 'furn', () => {
      dark.pipe(1.15, 1.5, x, drumY, z, 16)
      metal.pipe(0.9, 0.5, x, drumY + 1.5, z, 16)
      for (const dxx of [-1.05, 1.05]) metal.boxOn(0.28, 2.6, 0.6, x + dxx, drumY + 2.0, z)
      const tube = new THREE.CylinderGeometry(0.62, 0.72, 5.6, 20, 1)
      tube.rotateX(0.72)
      metal.add(tube, x, drumY + 3.6, z + 0.3)
      const ring = new THREE.CylinderGeometry(0.78, 0.78, 0.25, 20, 1)
      ring.rotateX(0.72)
      dark.add(ring, x, drumY + 2.9, z - 0.45)
    })
    // Рабочее место наблюдателя — масштаб для зала диаметром 16 м (furnish.ts).
    furnishDomeHall(KIT, { x, z, floor: drumY, r: R }, warm)

    // openEnded: у цилиндра по умолчанию есть донышко, и оно ложится сплошным
    // диском на отметке пола зала — поверх проёма лестницы. Снаружи этого
    // не видно (диск внутри), а подъём упирался в него головой.
    walls.add(new THREE.CylinderGeometry(R, R, drumH, 28, 1, true), x, drumY + drumH / 2, z)
    // кольцо мелких окон по барабану
    for (let i = 0; i < 12; i++) {
      const a = (i / 12) * Math.PI * 2
      glass.add(
        new THREE.PlaneGeometry(0.8, 0.9),
        x + Math.sin(a) * (R + 0.02),
        drumY + drumH * 0.7,
        z + Math.cos(a) * (R + 0.02),
        0,
        a,
        0,
      )
    }

    const domeY = drumY + drumH
    walls.add(new THREE.SphereGeometry(R + 0.2, 30, 16, 0, Math.PI * 2, 0, Math.PI / 2), x, domeY, z)
    // щель
    dark.box(1.5, 1.2, R * 2 + 1.2, x - R * 0.35, domeY + R * 0.62, z, 0)
  }

  // Пустой сборщик пропускается, и это не аккуратность: `mergeGeometries`
  // на пустом списке падает молча-непонятно (`geometries[0].index`). Пустым
  // сборщик стал ровно тогда, когда окна превратились в проёмы и «горящее
  // окно» перестало рисоваться краской — то есть от осмысленной правки.
  // Снежный слой (`snowify`) не должен работать внутри дома, а интерьер и фасад
  // слиты в один меш — отличить их можно только по координатам. Объёмы уходят
  // в шейдер: маска в вершинном атрибуте врала на больших плитах (см. `parts.ts`).
  setSnowShelters(interiors.rooms)
  for (const [p, mat, name] of [
    [walls, MAT.concrete, 'walls'],
    [dark, MAT.concreteDark, 'plinths'],
    // Рамы, створки, мебель и перила были в `MAT.concreteDark` — то есть бетоном.
    // Описка держалась с фазы 4 и в кадре читалась бетонным столом в дежурке.
    [metal, MAT.metal, 'frames'],
    [glass, MAT.glass, 'glass'],
    [pale, MAT.glassPale, 'glass-pale'],
    [lit, MAT.window, 'lit-windows'],
    [hot, MAT.doorway, 'doorway'],
    [snow, MAT.snow, 'roof-snow'],
    [icicles, MAT.icicle, 'icicles'],
    // Обстановка: бумага, ткань, эмаль — то, чем комната отличается от склада.
    [paper, MAT.paper, 'paper'],
    [cloth, MAT.cloth, 'cloth'],
    [enamel, MAT.enamel, 'enamel'],
    [wood, MAT.wood, 'wood'],
    [rust, MAT.rust, 'rust'],
  ] as [Parts, THREE.Material, string][]) {
    if (!p.empty) group.add(p.mesh(mat, name))
  }
  // Грязь идёт последней и с `renderOrder`: полупрозрачные накладки обязаны
  // рисоваться ПОСЛЕ стены, которую пачкают. Из буфера нормалей они исключены —
  // плоскость в двух сантиметрах от стены SSAO принимает за отдельную
  // поверхность и обводит её тенью (см. NO_NORMALS_LAYER).
  const grimeMesh = grime.mesh(MAT.grime, 'grime')
  grimeMesh.renderOrder = 1
  grimeMesh.layers.set(NO_NORMALS_LAYER)
  group.add(grimeMesh)
  // Оконные стёкла — тоже прозрачные накладки, и рисуются они последними:
  // сквозь них видно комнату, а комната обязана быть нарисована раньше.
  // В Octree стекло идёт как есть — в окно не пролезть.
  const paneMesh = pane.mesh(MAT.pane, 'panes')
  paneMesh.renderOrder = 2
  group.add(paneMesh)
  // Пятна на полу и столешницах — та же полупрозрачная накладка, что грязь
  // на фасаде, и по тем же правилам: рисуется после поверхности, из буфера
  // нормалей исключена (иначе SSAO обведёт круг от кружки тенью).
  if (!stain.empty) {
    const stainMesh = stain.mesh(MAT.stain, 'stains')
    stainMesh.renderOrder = 1
    stainMesh.layers.set(NO_NORMALS_LAYER)
    group.add(stainMesh)
  }
  return { group, warm, spill, interiors }
}
