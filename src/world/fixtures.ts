/**
 * fixtures.ts — реестр обстановки: что стоит в помещении и какого оно размера.
 *
 * Зачем он заведён. До этой сессии интерьер существовал только как вызовы
 * `metal.boxOn(...)` внутри `furnish()`: в кадре обстановку видно, в коде —
 * нет. Вопрос «не стоит ли шкаф поперёк двери» приходилось задавать браузеру,
 * то есть скриншотом или автопроходом — дорого и не каждый раз. Ровно так
 * полка в дежурке заперла выход и прожила целую сессию. Реестр отвечает на
 * такие вопросы счётом, на Node, за секунду (`npm run room`).
 *
 * Два правила, ради которых он устроен именно так:
 *
 * 1. **Габарит не переписывается числами, а снимается с геометрии.** Копия
 *    чисел разъезжается с оригиналом — на копиях формул рельефа в фазе 3.5
 *    разъехались три бага подряд, и мебель ничем не лучше. Поэтому `Parts.add`
 *    сообщает сюда рамку КАЖДОЙ добавленной геометрии, уже после матрицы:
 *    предмет получает ровно тот габарит, который встанет в кадре.
 * 2. **Комната предмету не назначается.** Она вычисляется по перекрытию
 *    с объёмами из `Interiors` — иначе появилось бы второе место, где живёт
 *    привязка, и оно бы разошлось с первым. Заодно это честно показывает
 *    предмет, наполовину вылезший в соседнее помещение.
 *
 * Файл намеренно БЕЗ ИМПОРТОВ, как `layout.ts`: голые числа и один стек.
 * Стоит он ничего — запись включена всегда, `computeBoundingBox` на паре
 * тысяч коробок при старте не мерится.
 */

/**
 * Роль предмета. От неё зависит и символ на плане, и то, чем предмет считается
 * при проверке прохода: сквозь `furn` не ходят, сквозь `stair` ходят вверх,
 * а `hang` под потолком проходу не мешает вовсе.
 */
export type Kind =
  /** Стены, перекрытия, косяки — то, что ограничивает объём. */
  | 'wall'
  /** Марш: объём занимает, но по нему ходят. */
  | 'stair'
  /** Стоящее на полу: мебель, приборы, бочки. */
  | 'furn'
  /** Висящее: трубы, лотки, полки, плафоны. Проходу не мешает, голове — да. */
  | 'hang'
  /** Окна и панели: видно, но не мешает. */
  | 'glass'
  /** Проём: дверь, через которую ходят. */
  | 'door'
  /** Мелочь ниже переступа: кружка, ящик, ведро, сапоги. */
  | 'small'
  /** Светящееся: плафоны, индикаторы, источники. */
  | 'light'

export type Fixture = {
  name: string
  kind: Kind
  x0: number
  x1: number
  y0: number
  y1: number
  z0: number
  z1: number
}

/** Всё, что зарегистрировано за сборку мира. */
export const FIXTURES: Fixture[] = []

/** Стек открытых предметов: `piece` внутри `piece` расширяет обоих. */
const stack: Fixture[] = []

const INF = Number.POSITIVE_INFINITY

/**
 * Отметить предмет: всё, что построено внутри `draw`, войдёт в его габарит.
 *
 * Возвращает то же, что `draw`, — чтобы обёртка вставлялась в существующий код
 * без разрыва выражений.
 */
export function piece<T>(name: string, kind: Kind, draw: () => T): T {
  const f: Fixture = { name, kind, x0: INF, x1: -INF, y0: INF, y1: -INF, z0: INF, z1: -INF }
  stack.push(f)
  try {
    return draw()
  } finally {
    stack.pop()
    // Предмет, не построивший ни одной геометрии (комната без марша, окно
    // за пределами стены), в реестр не идёт: пустая рамка на плане — мусор.
    if (f.x1 > f.x0) FIXTURES.push(f)
  }
}

/**
 * Рамка одной геометрии — из `Parts`. Числа мировые, матрица уже применена.
 *
 * Расширяет ВСЕ открытые предметы: у вложенного `piece` свой габарит, у
 * внешнего — общий. Пока стек пуст, вызов бесплатен, поэтому дёргать его
 * из `Parts` можно безусловно.
 */
export function noteBox(
  x0: number,
  y0: number,
  z0: number,
  x1: number,
  y1: number,
  z1: number,
): void {
  for (const f of stack) {
    if (x0 < f.x0) f.x0 = x0
    if (y0 < f.y0) f.y0 = y0
    if (z0 < f.z0) f.z0 = z0
    if (x1 > f.x1) f.x1 = x1
    if (y1 > f.y1) f.y1 = y1
    if (z1 > f.z1) f.z1 = z1
  }
}

/** Идёт ли запись. `Parts` спрашивает первым делом: пустой стек — ничего не считаем. */
export function recording(): boolean {
  return stack.length > 0
}

/** Сброс перед пересборкой мира. Замерялка строит мир дважды, браузер — один раз. */
export function clearFixtures(): void {
  FIXTURES.length = 0
  stack.length = 0
}
