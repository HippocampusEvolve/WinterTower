/**
 * materials.ts — общие материалы мира.
 *
 * Цвета берутся только из PALETTE (atmosphere.ts). Здесь задаётся лишь то,
 * как поверхность отвечает на свет: шероховатость, металличность, свечение.
 *
 * Фаза 4 добавила карты (`public/textures/*`, ambientCG, CC0). Правила, ради
 * которых заведён `pbr()`:
 *
 * 1. **Карта цвета берётся не всегда, и решает это замер, а не глаз.** Шейдер
 *    УМНОЖАЕТ карту на `color`, поэтому тёмная карта утаскивает вниз всю гамму,
 *    сведённую по референсу. Средние карт в линейном пространстве (замер в
 *    браузере по canvas): бетон 0.48, снег 0.58, гравий 0.20, металл 0.058,
 *    камень 0.074. Правило: если среднее не ниже ~0.4, карта цвета идёт в дело
 *    с компенсацией `colorGain = 1/среднее` — тогда поверхность в среднем
 *    остаётся ровно того цвета, что в палитре, а карта работает грязью
 *    и пятнами. Если ниже — от карты берутся ТОЛЬКО нормаль и шероховатость,
 *    цвет остаётся плоским из `PALETTE`. Компенсировать множителем 13–17
 *    бессмысленно: у такой карты почти весь диапазон в нуле, и вместо камня
 *    выходит чёрное поле с редкими белыми искрами.
 *    Карты цвета, не прошедшие порог (камень, гравий, а с фазы 13 — дерево,
 *    ржавчина, ткань, лёд, металл), поэтому вынесены из `public/` в
 *    `textures-unused/`: vite копирует `public` в `dist` целиком, и мегабайты
 *    уезжали в прод-сборку, ни разу не будучи запрошенными браузером.
 * 2. **Зерно задаётся в МЕТРАХ и одинаково у всей поверхности мира.** Раньше
 *    здесь стояло `tiles` — повторов на грань, — и это было ошибкой: UV
 *    примитивов идут 0…1 НА ГРАНЬ независимо от её размера, поэтому одно и то
 *    же число давало зерно 4 м на стене корпуса и 5 см на кабельном лотке.
 *    Узкие детали читались полосами другого материала при том же материале —
 *    несогласованная плотность текселей. Развёртку теперь считает `planarUV`
 *    в `parts.ts` (единица UV = метр мира), а материалу остаётся один множитель
 *    `meters`: сколько метров укладывается в один повтор картинки.
 * 3. **Карты грузятся лениво и асинхронно.** Мир строится синхронно на старте,
 *    и ждать сеть нельзя: пока карт нет, материал уже работает на цвете из
 *    палитры, а `needsUpdate` докладывает карту по готовности.
 * 4. **Карты лежат WebP q90, а не исходным JPEG, и РАЗМЕР НАПИСАН В ИМЕНИ.**
 *    ambientCG отдаёт JPEG качества ~100: три normal-карты весили почти по
 *    10 МБ, вся папка — 64 МБ. Перекодировка в WebP ужала её до 13 МБ, а
 *    пересчёт разрешения — до 3.9 МБ, и это второе оказалось важнее первого:
 *    вход в мир на канале 8 Мбит/с сократился с 13 до 8 секунд, а заставка
 *    загрузки перестала уходить по аварийному таймеру, не дождавшись карт.
 *
 *    Потолки: normal и color — 1024, rough и metal — 512. Взяты не на глаз:
 *    зерно задано в метрах, и карта 2048 при `meters` 2.4 давала 853 текселя
 *    на метр — на порядок больше, чем способен показать экран сквозь туман
 *    на сорока метрах. Кадр до и после неотличим, а `snow/rough` при этом
 *    ужалась с 1169 КБ до 14: карта почти ровная, и всё её содержимое было
 *    шумом разрешения.
 *
 *    Суффикс в имени (`normal_1k`, `rough_512`) — не украшение. Nginx отдаёт
 *    текстуры с годовым `immutable`, поэтому под прежним именем вернувшийся
 *    игрок год видел бы старую версию. Меняешь содержимое — меняй имя.
 *    Исходники лежат в `textures-unused/orig/` — новую карту прогонять тем же
 *    путём, как есть не класть.
 */

import * as THREE from 'three'
import { PALETTE } from '../atmosphere'

const std = (o: THREE.MeshStandardMaterialParameters) => new THREE.MeshStandardMaterial(o)

const loader = new THREE.TextureLoader()

/**
 * Файлы, уже отданные в загрузку, и клоны, ждущие свою картинку.
 *
 * Одна карта нужна нескольким материалам сразу: камень идёт и в рельеф, и в
 * валуны, и в осыпь; металл — в лестницу, настил и короба. А `loader.load`
 * на КАЖДЫЙ вызов заводит свой `<img>` и свою текстуру в видеопамяти, даже
 * если путь тот же самый. Замер до этого кэша: 40 картинок на 25 файлов и
 * 46 текстур в GPU вместо 25.
 *
 * Дублировалась не только память. Браузер, получив четыре десятка запросов
 * на два с половиной десятка адресов, доводил до конца лишь первые три-четыре,
 * а остальные держал открытыми, ожидая ответа по тому же адресу. Для
 * `LoadingManager` это значило, что счётчик застревал на 4 из 41 и `onLoad`
 * не приходил никогда — заставка загрузки уходила по предохранителю, а полоса
 * замирала на десятой доле.
 */
const files = new Map<string, THREE.Texture>()
const pending = new Map<string, THREE.Texture[]>()

/**
 * Один канал карты. `srgb` — только для цвета; нормали и шероховатость линейные.
 *
 * Проверка на DOM — не паранойя: `npm run measure` собирает НАСТОЯЩИЕ модули
 * мира и гоняет их на Node, а `TextureLoader` внутри дёргает
 * `document.createElementNS`. Без этой ветки замерялка падает от того, что
 * рельеф импортирует материалы. Пустая текстура ей подходит: она мерит
 * геометрию, а не картинку.
 */
function map(path: string, meters: number, srgb: boolean): THREE.Texture {
  if (typeof document === 'undefined') return new THREE.Texture()

  let base = files.get(path)
  if (!base) {
    const waiting: THREE.Texture[] = []
    pending.set(path, waiting)
    base = loader.load(path, () => {
      // Картинка пришла — клоны об этом сами не узнают: `TextureLoader` метит
      // только ту текстуру, которую вернул из `load`.
      for (const t of waiting) t.needsUpdate = true
      pending.delete(path)
    })
    base.wrapS = base.wrapT = THREE.RepeatWrapping
    if (srgb) base.colorSpace = THREE.SRGBColorSpace
    base.anisotropy = 8
    files.set(path, base)
  }

  // Зерно у каждого материала своё, а картинка одна на всех. Клон делит с
  // оригиналом `source`, поэтому в видеопамять карта уезжает единожды, а
  // repeat, offset и прочее у клона собственные.
  const t = base.clone()
  // UV приходят в метрах, поэтому повтор — обратная величина размера зерна.
  t.repeat.set(1 / meters, 1 / meters)

  const waiting = pending.get(path)
  if (waiting) {
    // `clone()` метит текстуру к заливке, а картинки ещё нет: рендерер будет
    // жаловаться на неполный `<img>` каждый кадр до её прихода. Сбрасываем
    // версию и поднимем её сами, когда файл догрузится.
    t.version = 0
    waiting.push(t)
  }
  return t
}

/**
 * Альфа-карта потёка: плотно вверху, к низу и к бокам сходит на нет,
 * с продольными прожилками — вода течёт струйками, а не пеленой.
 *
 * Рисуется в коде: качать текстуру ради одного градиента незачем, а на Node
 * (замерялка) `document` нет вовсе, поэтому здесь та же заглушка, что у `map`.
 */
function fadeTexture(): THREE.Texture {
  if (typeof document === 'undefined') return new THREE.Texture()
  const N = 64
  const c = document.createElement('canvas')
  c.width = c.height = N
  const ctx = c.getContext('2d')!
  const img = ctx.createImageData(N, N)
  for (let y = 0; y < N; y++) {
    // v: 0 сверху (плотно) → 1 снизу (пусто)
    const v = y / (N - 1)
    const down = Math.pow(1 - v, 1.5)
    for (let x = 0; x < N; x++) {
      const u = x / (N - 1)
      const side = Math.sin(Math.PI * u) // мягкие бока
      // Прожилки: несколько частот, чтобы полоса не была ровной заливкой.
      const veins = 0.55 + 0.45 * Math.abs(Math.sin(u * 11.3) * Math.sin(u * 4.1 + 1.7))
      const a = Math.max(0, Math.min(1, down * side * veins))
      const o = (y * N + x) * 4
      img.data[o] = img.data[o + 1] = img.data[o + 2] = 255
      img.data[o + 3] = Math.round(a * 255)
    }
  }
  ctx.putImageData(img, 0, 0)
  const t = new THREE.CanvasTexture(c)
  t.wrapS = t.wrapT = THREE.ClampToEdgeWrapping
  return t
}

/**
 * Альфа-карта пятна: плотно в середине, к краям сходит на нет, край рваный.
 *
 * Нужна там, где потёк не годится: круг от кружки на столе, натоптанное
 * у двери, масляное пятно под верстаком. `fadeTexture` льётся сверху вниз,
 * и повёрнутая горизонтально она даёт полосу поперёк стола, а не круг.
 */
function blotTexture(): THREE.Texture {
  if (typeof document === 'undefined') return new THREE.Texture()
  const N = 64
  const c = document.createElement('canvas')
  c.width = c.height = N
  const ctx = c.getContext('2d')!
  const img = ctx.createImageData(N, N)
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; x++) {
      const u = (x / (N - 1)) * 2 - 1
      const v = (y / (N - 1)) * 2 - 1
      const r = Math.hypot(u, v)
      // Край рваный: радиус гуляет по углу, иначе пятно — идеальный круг,
      // а идеальных кругов грязь не оставляет (урок подтёков фазы 6).
      const a = Math.atan2(v, u)
      const edge = 0.72 + 0.16 * Math.sin(a * 3.7) * Math.sin(a * 2.1 + 0.9)
      const k = Math.max(0, Math.min(1, 1 - (r / edge) ** 2.2))
      const o = (y * N + x) * 4
      img.data[o] = img.data[o + 1] = img.data[o + 2] = 255
      img.data[o + 3] = Math.round(k * 255)
    }
  }
  ctx.putImageData(img, 0, 0)
  const t = new THREE.CanvasTexture(c)
  t.wrapS = t.wrapT = THREE.ClampToEdgeWrapping
  return t
}

/**
 * Материал с картами из `public/textures/<name>/`.
 * `meters` — физический размер одного повтора картинки в метрах мира. Величина
 * абсолютная: зерно бетона 4 м лежит четырёхметровым и на двадцатиметровой
 * стене, и на двадцатисантиметровом лотке. Держится это на том, что развёртку
 * всей статики считает `planarUV` (`parts.ts`) в метрах.
 */
function pbr(
  name: string,
  o: THREE.MeshStandardMaterialParameters & { meters?: number; hasMetal?: boolean; colorGain?: number },
): THREE.MeshStandardMaterial {
  const { meters = 3, hasMetal = false, colorGain, ...rest } = o
  const m = std(rest)
  const base = `textures/${name}/`
  if (colorGain) {
    m.map = map(base + 'color_1k.webp', meters, true)
    // Компенсация среднего: карта в среднем даёт `1/colorGain`, множитель
    // возвращает поверхность к цвету палитры. Значение выше 1 в three законно —
    // цвет материала не обязан лежать в 0…1.
    m.color.multiplyScalar(colorGain)
  }
  // Размер в имени: см. правило 4 в шапке файла. Под прежним именем карта
  // не доехала бы до вернувшегося игрока — nginx отдаёт их с годовым immutable.
  m.normalMap = map(base + 'normal_1k.webp', meters, false)
  m.roughnessMap = map(base + 'rough_512.webp', meters, false)
  if (hasMetal) m.metalnessMap = map(base + 'metal_512.webp', meters, false)
  // Нормаль скачанного бетона рассчитана на плоскую стену в упор. В тумане
  // на 40 метрах она превращается в шум, поэтому давим её вдвое.
  m.normalScale = new THREE.Vector2(0.55, 0.55)
  return m
}

/**
 * Снежный слой — ОДНО решение на все поверхности мира.
 *
 * До фазы 10 снег был геометрией: плита на каждую верхнюю грань (`snowCap`).
 * Приём не спасала никакая форма, и причина у этого одна: накладной предмет
 * никогда не станет слоем. У плиты есть свои кромки, свой контур и свой зазор
 * с тем, на чём она лежит, — на ящике у стены она читалась крышкой, потому что
 * крышкой и была. Вещей, которые снег обязан делать, а плита не может, три:
 * лежать на КАЖДОЙ верхней грани без отдельного вызова, переходить с одной
 * поверхности на другую непрерывно и иметь рваный край, повторяющий рельеф
 * поверхности под собой.
 *
 * Отсюда слой в шейдере, и он делается в двух местах сразу:
 *
 * 1. **Вершинный шейдер поднимает поверхность** на `thickness` там, где она
 *    смотрит вверх (по `aSmooth` — усреднённой нормали, `parts.ts`). Это даёт
 *    снегу СИЛУЭТ: без вздутия слой остаётся краской и на кромке, снятой против
 *    неба, его не видно вовсе. На ребре средняя нормаль наклонена, подъём там
 *    меньше — кромка выходит скошенной сама.
 * 2. **Фрагментный шейдер красит** по нормали ПОСЛЕ карт: рябь нормали бетона
 *    рвёт край снега на сантиметровом масштабе, чего вершинами не добиться —
 *    и именно это отличает слой от покраски по маске.
 *
 * Порог по наклону мягкий (`slope`): снег держится и на слегка покатых гранях,
 * а на отвесах его нет. Шум по мировым координатам ломает и толщину, и край,
 * поэтому две соседние коробки не выглядят одинаково заснеженными.
 *
 * Чего слой НЕ знает: навесов. Под крышей снега нет по вершинному атрибуту
 * `aCover` (объёмы `Interiors`), но под кабельным лотком или карнизом он лежать
 * будет — для этого нужен запёкшийся сверху луч, а это отдельная работа.
 */
export const SNOW = {
  /** Толщина слоя в метрах: на сколько поднимается горизонтальная грань. */
  thickness: 0.1,
  /**
   * Свес за кромку, в долях толщины. Вершины ребра сдвигаются ещё и наружу —
   * по горизонтальной части средней нормали, — и слой перестаёт совпадать
   * с контуром предмета в плане. Без свеса снег читается покрашенной гранью:
   * у настоящего снега край всегда чуть шире того, на чём он лежит.
   */
  overhang: 0.45,
  /**
   * Компенсация яркости слоя, подобранная ЗАМЕРОМ, а не на глаз.
   *
   * Слой ЗАМЕЩАЕТ диффузный цвет вместе с картой, поэтому цвет палитры «как
   * есть» тут врёт: у бетона тот же `snowLit` домножен на `colorGain` 2.08,
   * а карта возвращает среднее назад. Замер кадра сверху: слой при gain 1 давал
   * яркость 75 против 141 у бетона рядом и 123 у снега земли — крыши уходили
   * в тёмно-синее.
   *
   * Но одним множителем это не лечится: у `snowLit` синий выше красного,
   * и на 2.3 зелёный с синим уходят ЗА единицу, а красный нет — крыша под
   * скользящим углом становилась неоновой бирюзой (та же ошибка, что в фазе 3,
   * когда перебор догонял абсолютный цвет референса). Поэтому яркость
   * поднимается вместе с расбеливанием (`desat`): цвет остаётся холодным, но
   * ни один канал не выбит. Замер при gain 1.7 / desat 0.4: сверху крыша
   * ложится рядом со снегом земли, ни один канал не в клиппинге.
   */
  gain: 1.7,
  /** Расбеливание цвета слоя: подмешать белого, чтобы каналы не выбивало. */
  desat: 0.4,
  /** Размер зерна шума в метрах: крупнее — длинные наносы, мельче — рябь. */
  grain: 1.1,
  /** Порог по наклону: 0.25 — снег уже держится, 0.55 — лежит целиком. */
  slope: new THREE.Vector2(0.25, 0.55),
  /** Тот же порог, но по нормали с картами: край рвётся её рябью. */
  face: new THREE.Vector2(0.3, 0.72),
}

/**
 * Укрытия: объёмы, внутри которых снега нет. Заполняются при сборке мира
 * (`buildings.ts`) из реестра помещений.
 *
 * Почему это UNIFORM, а не вершинный атрибут: первая версия слоя носила маску
 * «под крышей» в атрибуте, и на больших плитах она врала. У плиты пола вершины
 * только по углам, а углы цоколя лежат ЗА стенами помещения — интерполяция
 * давала единицу по всему полу, и в вестибюле шёл снег. Тесселировать плиты
 * ради маски нельзя (это геометрия ради шейдера), а объёмов всего десяток:
 * десять сравнений на пиксель дешевле любой лишней вершины.
 *
 * `w` в `min` — радиус: зал обсерватории круглый, и вписанный в него бокс
 * оставил бы полосу снега по краю пола, а описанный — съел бы снег с крыши
 * цоколя вокруг барабана.
 */
const MAX_SHELTERS = 16
const shelterMin = Array.from({ length: MAX_SHELTERS }, () => new THREE.Vector4())
const shelterMax = Array.from({ length: MAX_SHELTERS }, () => new THREE.Vector4())
const shelterCount = { value: 0 }

/**
 * Горизонтальный запас укрытия — на толщину стены, а не «чуть-чуть».
 *
 * Помещение регистрируется по ВНУТРЕННИМ граням стен, а пол под самой стеной
 * идёт насквозь: в дверном проёме он ничей — ни комнатин, ни коридорный.
 * С запасом в 5 см на пороге каждой двери лежала полоса уличного снега
 * шириной ровно в стену. Расширять маску безопасно: наружу от неё она уходит
 * в толщу бетона, а к земле у фасада выходит на 5 см — этого не видно.
 */
const SHELTER_PAD = 0.4

export function setSnowShelters(
  list: { x0: number; x1: number; y0: number; y1: number; z0: number; z1: number; r?: number }[],
): void {
  shelterCount.value = Math.min(list.length, MAX_SHELTERS)
  for (let i = 0; i < shelterCount.value; i++) {
    const r = list[i]
    // Пол помещения — граница объёма, и снег на нём должен быть погашен,
    // поэтому низ опускается, а верх поджимается: перекрытие сверху — это
    // уже КРЫША, и на ней снег обязан лежать.
    //
    // Круглому залу запас не даётся: дверей в барабане нет (в зал поднимаются
    // по маршу через проём в перекрытии), а раздутый радиус съел бы снег
    // с наружного пояса самого купола.
    const pad = r.r === undefined ? SHELTER_PAD : 0.05
    shelterMin[i].set(r.x0 - pad, r.y0 - 0.6, r.z0 - pad, r.r ?? 0)
    shelterMax[i].set(r.x1 + pad, r.y1 - 0.12, r.z1 + pad, 0)
  }
}

const SNOW_NOISE = /* glsl */ `
#define WT_SHELTERS 16
float wtHash(vec3 p) {
  return fract(sin(dot(p, vec3(12.9898, 78.233, 37.719))) * 43758.5453);
}
float wtNoise(vec3 p) {
  vec3 i = floor(p);
  vec3 f = fract(p);
  f = f * f * (3.0 - 2.0 * f);
  float n000 = wtHash(i);
  float n100 = wtHash(i + vec3(1.0, 0.0, 0.0));
  float n010 = wtHash(i + vec3(0.0, 1.0, 0.0));
  float n110 = wtHash(i + vec3(1.0, 1.0, 0.0));
  float n001 = wtHash(i + vec3(0.0, 0.0, 1.0));
  float n101 = wtHash(i + vec3(1.0, 0.0, 1.0));
  float n011 = wtHash(i + vec3(0.0, 1.0, 1.0));
  float n111 = wtHash(i + vec3(1.0, 1.0, 1.0));
  return mix(
    mix(mix(n000, n100, f.x), mix(n010, n110, f.x), f.y),
    mix(mix(n001, n101, f.x), mix(n011, n111, f.x), f.y),
    f.z
  );
}
/** Две октавы: крупные наносы плюс рябь. Одна давала ровную волну. */
float wtSnowNoise(vec3 p) {
  return 0.66 * wtNoise(p) + 0.34 * wtNoise(p * 2.7 + 11.3);
}
/** 0 внутри помещения (под крышей), 1 под открытым небом. */
float wtShelter(vec3 p) {
  for (int i = 0; i < WT_SHELTERS; i++) {
    if (i >= uShelterCount) break;
    vec4 lo = uShelterMin[i];
    vec4 hi = uShelterMax[i];
    if (p.y < lo.y || p.y > hi.y) continue;
    if (lo.w > 0.0) {
      vec2 c = vec2(lo.x + hi.x, lo.z + hi.z) * 0.5;
      if (dot(p.xz - c, p.xz - c) < lo.w * lo.w) return 0.0;
    } else if (p.x > lo.x && p.x < hi.x && p.z > lo.z && p.z < hi.z) {
      return 0.0;
    }
  }
  return 1.0;
}
`

/**
 * Навесить снежный слой на материал. Возвращает тот же материал — удобно
 * оборачивать прямо в объявлении `MAT`.
 *
 * `customProgramCacheKey` обязателен: без него three считает программы
 * одинаковыми по параметрам материала и может выдать обычному материалу
 * программу со снегом (и наоборот).
 */
function snowify(m: THREE.MeshStandardMaterial, mul = 1, tighten = 0): THREE.MeshStandardMaterial {
  const color = new THREE.Color(PALETTE.snowLit)
    .convertSRGBToLinear()
    .lerp(new THREE.Color(1, 1, 1), SNOW.desat)
    .multiplyScalar(SNOW.gain)
  m.onBeforeCompile = (shader) => {
    shader.uniforms.uSnowColor = { value: color }
    shader.uniforms.uShelterCount = shelterCount
    shader.uniforms.uShelterMin = { value: shelterMin }
    shader.uniforms.uShelterMax = { value: shelterMax }
    shader.uniforms.uSnowThick = { value: SNOW.thickness * mul }
    shader.uniforms.uSnowOver = { value: SNOW.thickness * mul * SNOW.overhang }
    shader.uniforms.uSnowGrain = { value: SNOW.grain }
    shader.uniforms.uSnowSlope = { value: SNOW.slope }
    // `tighten` поднимает порог по наклону для отдельного материала: на валунах
    // снег обязан лежать ПЯТНАМИ, а не покрывать их целиком, иначе осыпь
    // читается рядом сугробов (та же ошибка, что с нашлёпками в фазе 6).
    shader.uniforms.uSnowFace = { value: new THREE.Vector2(SNOW.face.x + tighten, SNOW.face.y + tighten) }
    shader.vertexShader = shader.vertexShader
      .replace(
        '#include <common>',
        `#include <common>
        attribute vec3 aSmooth;
        uniform float uSnowThick;
        uniform float uSnowOver;
        uniform float uSnowGrain;
        uniform vec2 uSnowSlope;
        uniform int uShelterCount;
        uniform vec4 uShelterMin[16];
        uniform vec4 uShelterMax[16];
        varying float vSnowUp;
        varying vec3 vSnowWorld;
        ${SNOW_NOISE}`,
      )
      .replace(
        '#include <begin_vertex>',
        `#include <begin_vertex>
        vSnowUp = clamp(aSmooth.y, 0.0, 1.0);
        vSnowWorld = (modelMatrix * vec4(transformed, 1.0)).xyz;
        float snowUp = smoothstep(uSnowSlope.x, uSnowSlope.y, vSnowUp) * wtShelter(vSnowWorld);
        // Толщина гуляет вдвое: ровный слой одной высоты — это опять плита.
        float snowN = wtSnowNoise(vSnowWorld / uSnowGrain);
        transformed.y += uSnowThick * snowUp * (0.45 + 1.1 * snowN);
        // Свес: на РЕБРЕ средняя нормаль наклонена, её горизонтальная часть и
        // указывает наружу от предмета. На плоской грани она нулевая, поэтому
        // раздувается ровно кромка, а не всё тело.
        transformed.xz += aSmooth.xz * uSnowOver * snowUp * (0.5 + snowN);`,
      )
    shader.fragmentShader = shader.fragmentShader
      .replace(
        '#include <common>',
        `#include <common>
        uniform vec3 uSnowColor;
        uniform float uSnowGrain;
        uniform vec2 uSnowSlope;
        uniform vec2 uSnowFace;
        uniform int uShelterCount;
        uniform vec4 uShelterMin[16];
        uniform vec4 uShelterMax[16];
        varying float vSnowUp;
        varying vec3 vSnowWorld;
        ${SNOW_NOISE}`,
      )
      .replace(
        '#include <normal_fragment_maps>',
        `#include <normal_fragment_maps>
        {
          // normal здесь — в пространстве КАМЕРЫ, а не мира: в three нормали
          // во фрагментном шейдере приходят view-space. Первая версия слоя
          // спрашивала у неё «смотришь ли вверх» и получала вертикаль камеры —
          // снег то появлялся, то исчезал от поворота головы, а на кадре
          // сверху его не было вовсе. Обратный переход в мир — умножение
          // СПРАВА на viewMatrix: она ортонормирована, поэтому это и есть
          // умножение на обратную (viewMatrix ортонормирована).
          vec3 wn = normalize((vec4(normal, 0.0) * viewMatrix).xyz);
          // Край рвётся ДВАЖДЫ: рябью нормали (мелкий масштаб) и шумом
          // по мировым координатам (крупный). Одного мало: по нормали край
          // выходит равномерно шершавым, по шуму — гладко волнистым.
          float snowN = wtSnowNoise(vSnowWorld / uSnowGrain);
          float bias = (snowN - 0.5) * 0.34;
          float snowFace = smoothstep(uSnowFace.x + bias, uSnowFace.y + bias, clamp(wn.y, 0.0, 1.0));
          // Отвес остаётся отвесом даже если карта завалила ему нормаль.
          float snow = snowFace * smoothstep(uSnowSlope.x * 0.4, uSnowSlope.y, vSnowUp) * wtShelter(vSnowWorld);
          // Слой замещает карту целиком, поэтому зерно ему нужно своё:
          // без него снег выходит гладкой краской, заметной именно на больших
          // поверхностях вроде крыши.
          vec3 snowRGB = uSnowColor * (0.88 + 0.24 * wtSnowNoise(vSnowWorld * 7.0));
          diffuseColor.rgb = mix(diffuseColor.rgb, snowRGB, snow);
          roughnessFactor = mix(roughnessFactor, 0.95, snow);
          metalnessFactor = mix(metalnessFactor, 0.0, snow);
          // Нормаль подтягивается вверх: слой снега сглаживает то, на чём лежит.
          // Вертикаль мира тоже переводится в пространство камеры, иначе она
          // указывала бы «вверх по экрану».
          vec3 upView = normalize((viewMatrix * vec4(0.0, 1.0, 0.0, 0.0)).xyz);
          normal = normalize(mix(normal, upView, snow * 0.75));
        }`,
      )
  }
  m.customProgramCacheKey = () => 'wt-snow-' + mul.toFixed(2) + '-' + tighten.toFixed(2)
  return m
}

