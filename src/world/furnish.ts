/**
 * furnish.ts — обстановка помещений: мебель, оборудование и вещи людей.
 *
 * Отделено от `buildings.ts` по той же причине, по которой профиль лестницы
 * отделён от её коробок: здание — это стены, проёмы и перекрытия, а обстановка
 * меняется каждую сессию и растёт быстрее всего остального. К фазе 8 половина
 * `buildings.ts` была расстановкой стульев.
 *
 * Сборщики геометрии приходят снаружи (`Kit`), поэтому обратного импорта нет:
 * `buildings` знает про `furnish`, `furnish` про `buildings` — нет.
 *
 * **Каждый предмет обёрнут в `piece`** (`fixtures.ts`), и это обязательное
 * условие, а не украшение: реестр — единственный способ увидеть комнату,
 * не заходя в неё (`npm run room`). Не обёрнутый предмет для карты не
 * существует, и проверка «шкаф в створе двери» его пропустит.
 *
 * Правило расстановки, которое здесь работает всегда: **живость — это не
 * предметы, а следы людей.** Стол, шкаф и стеллаж делают комнату складом;
 * комнату жилой делают кружка на столе, куртка на крючке, стопка бумаг
 * и круг от кружки на столешнице. Стоят они копейки — коробка, цилиндр,
 * накладка, — а читаются сильнее любой мебели.
 */

import * as THREE from 'three'
import { Parts } from './parts'
import { piece } from './fixtures'
import { keepUV } from './parts'
import type { Warm } from './glow'

/** Сборщики, в которые кладётся обстановка. Приходят из `buildings.ts`. */
export type Kit = {
  /** Светлый обмёрзший металл: мебель, рамы, трубы. */
  metal: Parts
  /** Тёмный бетон и железо: печь, бочки, ящики. */
  dark: Parts
  /** Светящееся: плафоны, индикаторы. */
  hot: Parts
  /** Бумага: журналы, карты, календари. */
  paper: Parts
  /** Ткань: куртки, плед, ветошь. */
  cloth: Parts
  /** Эмаль: кружки, чайники, миски. */
  enamel: Parts
  /** Дерево: поленья, доски, скамьи, конторка, поддоны. */
  wood: Parts
  /** Ржавое железо: бочки, баки, вёдра, контейнер. */
  rust: Parts
  /** Накладки пятен на пол и столешницы. */
  stain: Parts
}

/** Комната корпуса: внутренние границы, пол, высота, створ двери в коридор. */
export type RoomBox = {
  name: string
  x0: number
  x1: number
  z0: number
  z1: number
  floor: number
  h: number
  /** Центр проёма в коридор (по Z) и его ширина. */
  door: number
  doorW: number
}

// --- Мелочь ------------------------------------------------------------------
// Всё, что ниже, — вещи размером с ладонь. Каждая вещь идёт в реестр отдельным
// предметом: на плане они не видны (клетка 25 см), а в таблице видны, и
// проверка «не в стене ли» работает и для кружки.

/** Кружка: стакан с ручкой. Главный предмет этого файла. */
function mug(k: Kit, x: number, y: number, z: number) {
  piece('кружка', 'small', () => {
    k.enamel.pipe(0.042, 0.095, x, y, z, 8)
    k.enamel.box(0.02, 0.055, 0.03, x + 0.05, y + 0.055, z)
  })
}

/** Стопка бумаг или раскрытый журнал: плоская светлая коробка. */
function papers(k: Kit, x: number, y: number, z: number, w = 0.3, d = 0.22, ry = 0) {
  piece('бумаги', 'small', () => k.paper.boxOn(w, 0.025, d, x, y, z, ry))
}

/** Чайник на печи или на плитке. */
function kettle(k: Kit, x: number, y: number, z: number) {
  piece('чайник', 'small', () => {
    k.enamel.pipe(0.1, 0.16, x, y, z, 10)
    k.enamel.pipe(0.04, 0.05, x, y + 0.16, z, 6)
    k.enamel.strut(0.012, x - 0.09, y + 0.09, z, x - 0.15, y + 0.13, z)
  })
}

/** Ящик: тара, на которой всё в этом мире стоит и лежит. */
function crate(k: Kit, x: number, y: number, z: number, w = 0.5, h = 0.35, d = 0.38, ry = 0) {
  piece('ящик', 'small', () => {
    k.wood.boxOn(w, h, d, x, y, z, ry)
    // Стяжка ПОВЕРХ крышки, а не заподлицо с ней: вровень её верх ложился в ту
    // же плоскость, что верх ящика, и обе грани смотрели вверх - полоса поперёк
    // каждого ящика, а их в мире полтора десятка.
    k.metal.boxOn(w * 1.02, 0.03, d * 0.2, x, y + h - 0.01, z, ry)
  })
}

/**
 * Куртка или комбинезон на крючке. Роль `hang`, а не `small`: под ней пусто
 * по построению, и проверка «мебель висит в воздухе» иначе ловит её каждый раз.
 */
function coat(k: Kit, x: number, y: number, z: number, axis: 'x' | 'z' = 'z') {
  piece('куртка', 'hang', () => {
    const w = axis === 'z' ? 0.16 : 0.42
    const d = axis === 'z' ? 0.42 : 0.16
    k.cloth.boxOn(w, 0.62, d, x, y - 0.62, z)
    k.cloth.boxOn(w * 0.9, 0.3, d * 0.75, x, y - 0.92, z)
  })
}

/** Пятно на горизонтальной поверхности: круг от кружки, натоптанное, масло. */
function blot(k: Kit, x: number, y: number, z: number, r: number) {
  piece('пятно', 'small', () =>
    k.stain.add(keepUV(new THREE.PlaneGeometry(r * 2, r * 2)), x, y + 0.008, z, -Math.PI / 2, 0, 0),
  )
}

/**
 * Лист на стене: карта, календарь, график дежурств. Смотрит в −X или +Z.
 * Роль `hang` — он держится стеной, и опоры под ним нет по построению.
 */
function sheet(k: Kit, x: number, y: number, z: number, w: number, h: number, face: 'x' | 'z') {
  piece('лист', 'hang', () => {
    if (face === 'x') k.paper.box(0.012, h, w, x, y, z)
    else k.paper.box(w, h, 0.012, x, y, z)
  })
}

/**
 * Плафон под потолком. Станция брошена, и он НЕ горит: до фазы 12 это была
 * светящаяся коробка со своим источником, теперь — тёмное стекло на подвесе.
 *
 * Роль `light` в реестре осталась: она про то, что предмет висит под потолком
 * и в проходе не мешает, а не про то, что он светится.
 */
function ceilingLamp(k: Kit, x: number, yCeil: number, z: number): number {
  const ly = yCeil - 0.28
  piece('плафон', 'light', () => {
    k.metal.pipe(0.02, 0.24, x, ly, z, 5)
    k.dark.box(0.44, 0.12, 0.44, x, ly, z)
  })
  return ly
}

/**
 * Сумерки в помещении — слабый ХОЛОДНЫЙ источник у окна.
 *
 * Это не лампа: света на станции нет, но комната, освещённая ничем, читается
 * чёрным прямоугольником, а не заброшенной комнатой. В синий час через окно
 * идёт та же светящаяся мгла, что снаружи, и она — единственное, что здесь
 * светит. Цвет взят от неба (`PALETTE.skyBottom`), мощность на порядок меньше
 * прежних ламп: 3 против 13 в дежурке.
 */
function dusk(group: THREE.Group, x: number, y: number, z: number, power = 3, reach = 13): void {
  const l = new THREE.PointLight(0x9fc2da, power, reach, 2)
  l.position.set(x, y, z)
  group.add(l)
}

// --- Комнаты служебного корпуса ----------------------------------------------

/**
 * Обстановка помещения. Нужна не ради обстановки: пустая комната читается
 * коробкой, и человеческий масштаб внутри задают именно стол со скамьёй.
 * Свет ставится не везде — станция полупустая, и правило «3–4 тёплых пятна»
 * держится тем, что жилая только дежурка, а в остальных комнатах дежурное
 * освещение слабое.
 */
export function furnishRoom(k: Kit, r: RoomBox, group: THREE.Group, warm: Warm[]): void {
  /**
   * Створ двери в коридор. Всё, что стоит у стены коридора, обязано его
   * обходить: шкаф поперёк проёма невидим в кадре и не виден в коде — он
   * ловится только ногами. Ровно так полка в дежурке заперла выход.
   */
  const blocksDoor = (z: number, depth: number) => Math.abs(z - r.door) < r.doorW / 2 + depth / 2 + 0.4
  const { x0, x1, z0, z1, floor, h: H } = r
  const cx = (x0 + x1) / 2
  const cz = (z0 + z1) / 2
  const fl = floor + 0.02

  if (r.name === 'дежурка') {
    // Стол у окна, две скамьи вдоль него.
    const tx = cx - 1.6
    const tz = cz + 1.2
    const top = fl + 0.8
    piece('стол', 'furn', () => {
      k.wood.boxOn(1.9, 0.06, 0.85, tx, fl + 0.74, tz)
      for (const dx of [-0.8, 0.8])
        for (const dz of [-0.36, 0.36]) k.metal.pipe(0.035, 0.74, tx + dx, fl, tz + dz, 5)
    })
    for (const dz of [-0.75, 0.75]) {
      piece('скамья', 'furn', () => {
        k.wood.boxOn(1.7, 0.05, 0.3, tx, fl + 0.45, tz + dz)
        for (const dx of [-0.7, 0.7]) k.metal.pipe(0.03, 0.45, tx + dx, fl, tz + dz, 5)
      })
    }
    // На столе — вечер дежурства: две кружки, чайник, журнал, круги от кружек.
    mug(k, tx - 0.55, top, tz - 0.15)
    mug(k, tx + 0.35, top, tz + 0.2)
    kettle(k, tx + 0.75, top, tz - 0.2)
    papers(k, tx - 0.1, top, tz + 0.1, 0.34, 0.26, 0.3)
    blot(k, tx - 0.25, top, tz - 0.25, 0.07)
    blot(k, tx + 0.15, top, tz - 0.3, 0.05)
    // Куртка, брошенная на скамью. Двумя кусками под углом друг к другу:
    // одна коробка читается коробкой, чем бы её ни красили, — то же правило,
    // что у валунов фазы 6 (сплющенный икосаэдр не камень).
    piece('куртка', 'small', () => {
      k.cloth.boxOn(0.5, 0.14, 0.32, tx + 0.5, fl + 0.5, tz - 0.75, 0.22)
      k.cloth.boxOn(0.3, 0.11, 0.26, tx + 0.72, fl + 0.55, tz - 0.68, -0.4)
    })

    // Шкафы-пеналы у глухой стены, полка НАД ними.
    // До фазы 8 полка стояла на 1.5 м — то есть внутри шкафов: перекрытие
    // 0.34 × 0.27 × 0.55 м, найдено первым же запуском `npm run room`.
    // В кадре этого не видно никогда: обе вещи у стены, одна в другой.
    for (let i = 0; i < 3; i++)
      piece('шкаф', 'furn', () => k.metal.boxOn(0.62, 1.95, 0.55, x1 - 0.42, fl, z0 + 1.1 + i * 0.66))
    const shelfZ = z0 + 1.9
    piece('полка', 'hang', () => {
      k.metal.boxOn(0.34, 0.05, 2.2, x1 - 0.3, fl + 2.15, shelfZ)
      for (let i = 0; i < 4; i++) k.dark.boxOn(0.26, 0.22, 0.34, x1 - 0.3, fl + 2.2, shelfZ - 0.9 + i * 0.52)
    })
    // Печь с трубой в потолок — источник тепла и повод для тёплого света.
    const px = x1 - 0.6
    const pz = z1 - 1.4
    piece('печь', 'furn', () => {
      k.dark.boxOn(0.7, 0.95, 0.7, px, fl, pz)
      k.metal.pipe(0.09, H - 0.95, px, fl + 0.95, pz, 8)
      k.hot.add(new THREE.PlaneGeometry(0.42, 0.36), px - 0.36, fl + 0.55, pz, 0, -Math.PI / 2, 0)
    })
    kettle(k, px, fl + 0.95, pz)
    crate(k, px - 0.75, fl, pz - 0.15, 0.45, 0.32, 0.4, 0.2) // ящик с углём
    for (const [bx, bz] of [
      [x0 + 0.7, z0 + 0.8],
      [x0 + 1.3, z0 + 0.6],
    ])
      piece('ведро', 'small', () => k.metal.pipe(0.16, 0.3, bx, fl, bz, 7))
    // График дежурств у двери и календарь у стола — то, на что здесь смотрят.
    sheet(k, x1 - 0.03, fl + 1.6, r.door - 1.4, 0.42, 0.58, 'x')
    sheet(k, x1 - 0.03, fl + 1.55, z1 - 2.6, 0.3, 0.42, 'x')
    // Натоптанное перед дверью: единственное место комнаты, где ходят всегда.
    blot(k, x1 - 0.75, fl, r.door, 0.55)

    ceilingLamp(k, cx, floor + H, cz)
    dusk(group, x0 + 1.2, floor + 2.2, cz, 3, 12)

    // --- Печь ещё тёплая ------------------------------------------------------
    // Единственный живой огонь станции и вся её история в одном предмете: людей
    // нет давно (пыль, наледь, тёмные окна), но кто-то заходил несколько часов
    // назад — растопил печь, поставил чайник и ушёл. Свет от неё низкий
    // и короткий (радиус 7 против 11 у прежней лампы): он лижет пол и стену
    // рядом, а не заливает комнату, — так читается огонь, а не лампочка.
    const glow = new THREE.PointLight(0xff8a3c, 8, 7, 2)
    glow.position.set(px - 0.55, fl + 0.5, pz)
    group.add(glow)
    warm.push({
      pos: new THREE.Vector3(px - 0.42, fl + 0.55, pz),
      color: 0xff8a3c,
      size: 1.2,
      power: 0.45,
      label: 'печь в дежурке',
    })
    // Дрова, принесённые с собой: три полена у топки. Их не было в обжитой
    // версии комнаты — там уголь в ящике, а это след конкретного гостя.
    // Лежачий цилиндр строится `strut` (от точки до точки), а не `pipe`:
    // тот всегда вертикальный, и класть его набок пришлось бы поворотом
    // геометрии — правило `Parts.add` про наклон и рыскание.
    //
    // Лежат ЗА ящиком с углём, а не в нём. Прежние концы (`px − 0.74`)
    // заходили ящику под бок на 23 см: полено торчало сквозь доску, и в кадре
    // это читалось ровно тем, чем было, — двумя предметами в одном месте.
    // Габаритами их не поймать, ящик выше полена, и проверка считает такое
    // «задвинутым под» (см. `tools/room.ts`), поэтому число тут явное:
    // левый бок ящика — `px − 0.975`, дрова кончаются раньше.
    for (const [dz, skew, y] of [
      [-0.06, 0.06, 0.06],
      [0.2, -0.13, 0.06],
      [0.08, 0.05, 0.17],
    ] as const) {
      piece('полено', 'small', () =>
        k.wood.strut(0.055, px - 1.5, fl + y, pz + dz, px - 1.08, fl + y, pz + dz + skew, 6),
      )
    }
    return
  }

  if (r.name === 'аппаратная') {
    // Два ряда стоек с приборами, между ними проход. Индикаторы — единственное,
    // что светится: комната дежурная, людей в ней нет.
    for (const bx of [x1 - 0.5, x1 - 2.3]) {
      for (let z = z0 + 1.4; z < z1 - 1.4; z += 1.05) {
        if (bx > x1 - 1.2 && blocksDoor(z, 0.95)) continue
        piece('стойка', 'furn', () => {
          k.metal.boxOn(0.8, 2.05, 0.95, bx, fl, z)
          k.dark.box(0.06, 1.5, 0.85, bx - 0.42, fl + 1.2, z)
          for (let i = 0; i < 3; i++) k.hot.box(0.03, 0.05, 0.05, bx - 0.46, fl + 1.05 + i * 0.22, z - 0.2)
        })
      }
    }
    // Кабельный лоток под потолком вдоль всей комнаты.
    piece('лоток', 'hang', () => {
      k.metal.box(0.4, 0.08, z1 - z0 - 0.4, x1 - 1.4, floor + H - 0.5, cz)
      for (let z = z0 + 1; z < z1 - 1; z += 2.4)
        k.metal.strut(0.03, x1 - 1.4, floor + H - 0.46, z, x1 - 1.4, floor + H, z)
    })
    // Стол оператора у окна: журнал наблюдений, кружка, лампа под колпаком.
    const tx = x0 + 1.5
    const tz = cz + 2
    const top = fl + 0.81
    piece('стол', 'furn', () => {
      k.metal.boxOn(2.2, 0.06, 0.8, tx, fl + 0.75, tz)
      for (const dx of [-0.95, 0.95])
        for (const dz of [-0.32, 0.32]) k.metal.pipe(0.035, 0.75, tx + dx, fl, tz + dz, 5)
    })
    papers(k, tx - 0.3, top, tz, 0.44, 0.32, -0.12)
    papers(k, tx + 0.45, top, tz + 0.12, 0.28, 0.2, 0.4)
    mug(k, tx + 0.1, top, tz - 0.25)
    blot(k, tx + 0.1, top, tz - 0.25, 0.06)
    piece('стул', 'furn', () => {
      k.metal.boxOn(0.46, 0.05, 0.46, tx + 0.2, fl + 0.45, tz + 0.85)
      k.metal.pipe(0.05, 0.45, tx + 0.2, fl, tz + 0.85, 6)
      k.metal.box(0.46, 0.5, 0.05, tx + 0.2, fl + 0.75, tz + 1.07)
    })
    // Схема станции на стене между стойками.
    sheet(k, x1 - 2.85, fl + 1.7, z0 + 1.2, 0.9, 0.64, 'x')

    ceilingLamp(k, cx, floor + H, cz)
    // Индикаторы на стойках оставлены гореть: аварийное питание живёт дольше
    // людей, и красная искра в тёмной комнате говорит о станции больше, чем
    // погашенное всё. Общего света в комнате нет — только сумерки из окна.
    dusk(group, x0 + 1.4, floor + 2.2, cz, 3.4, 15)
    return
  }

  if (r.name === 'мастерская') {
    // Верстак вдоль фасада, тиски, бочки, стеллажи под стеной коридора.
    const bx = x0 + 0.7
    const bz = cz + 1
    piece('верстак', 'furn', () => {
      k.wood.boxOn(0.9, 0.05, 4.2, bx, fl + 0.88, bz)
      for (const dz of [-1.9, 0, 1.9])
        for (const dx of [-0.35, 0.35]) k.metal.pipe(0.04, 0.88, bx + dx, fl, bz + dz, 5)
    })
    piece('тиски', 'small', () => k.dark.boxOn(0.3, 0.28, 0.3, bx, fl + 0.93, bz + 1.4))
    // На верстаке — работа, брошенная на середине.
    for (const [dz, len] of [
      [-1.5, 0.34],
      [-1.15, 0.22],
      [0.4, 0.28],
    ] as const) {
      piece('инструмент', 'small', () => k.metal.boxOn(0.07, 0.035, len, bx + 0.12, fl + 0.93, bz + dz))
    }
    piece('ветошь', 'small', () => k.cloth.boxOn(0.26, 0.06, 0.3, bx - 0.2, fl + 0.93, bz - 0.6))
    mug(k, bx + 0.25, fl + 0.93, bz + 0.9)
    blot(k, bx, fl, bz - 0.4, 0.65) // масло под верстаком

    // Стеллажи: два вместо трёх и короче. Третий уходил в стену на 0.40 м —
    // нашлось `npm run room`, в кадре не видно (он за спиной у входящего).
    for (const sz of [z0 + 1.9, z1 - 1.9]) {
      if (blocksDoor(sz, 3.0)) continue
      piece('стеллаж', 'furn', () => {
        k.metal.boxOn(0.5, 2.1, 3.0, x1 - 0.35, fl, sz)
        // Полка выступает из тела стеллажа на 2 см, а не на 1: сантиметр - это
        // ровно порог, за которым две параллельные грани ещё спорят за глубину.
        for (let i = 1; i < 4; i++) k.dark.box(0.54, 0.05, 2.9, x1 - 0.35, fl + i * 0.52, sz)
      })
      // На полках — то, ради чего стеллаж и стоит.
      for (let i = 0; i < 4; i++) {
        crate(k, x1 - 0.35, fl + 0.52 + (i % 3) * 0.52, sz - 1.1 + i * 0.7, 0.34, 0.24, 0.3)
      }
    }
    for (const [ox, oz] of [
      [x0 + 2.6, z0 + 1.2],
      [x0 + 3.4, z0 + 1.9],
      [x0 + 2.2, z1 - 1.4],
    ])
      piece('бочка', 'furn', () => k.rust.pipe(0.32, 0.88, ox, fl, oz, 10))
    for (let i = 0; i < 4; i++)
      piece('ящик', 'small', () => k.dark.boxOn(0.55, 0.4, 0.7, x0 + 4.5, fl + i * 0.4, z1 - 2.6))

    ceilingLamp(k, cx, floor + H, cz - 2)
    ceilingLamp(k, cx, floor + H, cz + 3)
    dusk(group, x0 + 1.2, floor + 2.2, cz, 3.2, 14)
    return
  }

  if (r.name === 'сушилка') {
    // Тесная комната у выхода: скамья, штанга с крючками, сапоги под ней.
    piece('скамья', 'furn', () => {
      k.wood.boxOn(0.55, 0.06, 2.6, x0 + 0.6, fl + 0.45, cz)
      for (const dz of [-1.1, 1.1]) k.metal.pipe(0.04, 0.45, x0 + 0.6, fl, cz + dz, 5)
    })
    // Штанга ушла от середины комнаты к стене (было x0 + 1.6) и поднялась
    // с 1.85 до 2.05: крючки свисали на 1.67 м, а макушка капсулы на 2.02 —
    // в неё упирались головой ровно посреди прохода.
    const hx = x0 + 0.75
    piece('штанга с крючками', 'hang', () => {
      k.metal.strut(0.035, hx, floor + 2.2, cz - 1.4, hx, floor + 2.2, cz + 1.4)
      for (let i = 0; i < 5; i++) k.metal.pipe(0.02, 0.16, hx, floor + 2.04, cz - 1.2 + i * 0.6, 4)
    })
    // На крючках — то, ради чего сушилка существует.
    for (const dz of [-1.2, -0.6, 0.6]) coat(k, hx, floor + 2.04, cz + dz)
    for (let i = 0; i < 3; i++)
      piece('сапоги', 'small', () => k.dark.pipe(0.13, 0.42, x0 + 0.5 + i * 0.35, fl, cz - 0.9 - i * 0.2, 6))
    blot(k, x0 + 0.9, fl, cz - 0.6, 0.5) // натекло с одежды
    // Радиатор у наружной стены: единственное, что здесь греет.
    piece('радиатор', 'hang', () => {
      for (let i = 0; i < 7; i++) k.metal.pipe(0.05, 0.7, x0 + 0.18, fl + 0.25, z0 + 1 + i * 0.16, 5)
    })
    piece('варежки', 'small', () => k.cloth.boxOn(0.22, 0.05, 0.16, x0 + 0.25, fl + 0.95, z0 + 1.3))
    ceilingLamp(k, cx, floor + H, cz)
    dusk(group, x0 + 1.2, floor + 2.1, cz, 2.2, 9)
    return
  }
}

/** Коридор: лампы через равные промежутки, щиток, трубы и следы под ногами. */
export function furnishCorridor(
  k: Kit,
  o: { i: number; x0: number; x1: number; z0: number; z1: number; floor: number; h: number },
  group: THREE.Group,
): void {
  const cx = (o.x0 + o.x1) / 2
  const cz = (o.z0 + o.z1) / 2
  const H = o.h
  // Труба отопления вдоль всего коридора — она же связывает секции взглядом.
  piece('труба отопления', 'hang', () =>
    k.metal.box(0.09, 0.09, o.z1 - o.z0 - 0.7, o.x1 - 0.25, o.floor + H - 0.35, cz),
  )
  for (let z = o.z0 + 2; z < o.z1 - 1; z += 4.5) {
    piece('плафон', 'light', () => {
      k.metal.pipe(0.02, 0.2, cx, o.floor + H - 0.24, z, 5)
      k.dark.box(0.32, 0.09, 0.32, cx, o.floor + H - 0.28, z)
    })
  }
  // Коридор глухой: окон в нём нет, и светить в нём нечему. Оставлен только
  // отблеск из дверных проёмов — иначе проход между секциями чёрный настолько,
  // что по нему не пройти даже зная планировку.
  dusk(group, cx, o.floor + 2.0, cz, 1.6, 9)
  // Щиток на глухой стене.
  piece('щиток', 'hang', () =>
    k.dark.box(0.12, 0.7, 0.5, o.x1 - 0.06, o.floor + 1.5, o.z0 + 2.2 + o.i * 0.3),
  )
  // Доска объявлений: три листа под стеклом — самая дешёвая жизнь из всех.
  sheet(k, o.x1 - 0.05, o.floor + 1.6, cz + 1.6, 0.5, 0.7, 'x')
  sheet(k, o.x1 - 0.05, o.floor + 1.55, cz + 2.3, 0.3, 0.42, 'x')
  // Огнетушитель и ведро с песком у стены — обязательная часть станции.
  piece('огнетушитель', 'small', () => {
    k.dark.pipe(0.08, 0.42, o.x0 + 0.22, o.floor + 0.55, cz - 2.2, 8)
    k.metal.box(0.14, 0.06, 0.14, o.x0 + 0.22, o.floor + 0.52, cz - 2.2)
  })
  blot(k, cx, o.floor, cz, 1.1) // натоптанная полоса по оси коридора
}

// --- Операторская, вестибюль, зал --------------------------------------------

/**
 * Операторская центрального корпуса: пульты вдоль ленты окон, шкафы у дальней
 * стены, стол посреди зала. Смотровая сторона у людей та же, что у окон.
 */
export function furnishCore(
  k: Kit,
  o: { x0: number; x1: number; z0: number; z1: number; floor: number; h: number; wallT: number; winFrom: number },
  group: THREE.Group,
): void {
  const { x0, x1, z0, z1, floor } = o
  const fl = floor + 0.02
  const zIn = z1 - o.wallT
  for (let x = x0 + o.winFrom - 0.6; x < x1 - 2.4; x += 2.6) {
    piece('пульт', 'furn', () => {
      k.metal.boxOn(2.1, 0.75, 0.9, x, fl, zIn - 1.1)
      k.dark.box(2.0, 0.5, 0.12, x, fl + 1.05, zIn - 1.4)
      for (let i = 0; i < 4; i++) k.hot.box(0.05, 0.05, 0.03, x - 0.7 + i * 0.35, fl + 1.05, zIn - 1.47)
    })
    piece('стул', 'furn', () => {
      k.metal.boxOn(0.5, 0.05, 0.5, x, fl + 0.45, zIn - 2.1)
      k.metal.pipe(0.05, 0.45, x, fl, zIn - 2.1, 6)
      k.metal.box(0.5, 0.5, 0.05, x, fl + 0.75, zIn - 2.33)
    })
  }
  // Вахта идёт прямо сейчас: на первом пульте кружка и раскрытый журнал,
  // на спинке стула — куртка. Больше нигде: людей на станции мало.
  {
    const x = x0 + o.winFrom - 0.6
    mug(k, x - 0.85, fl + 0.77, zIn - 1.0)
    blot(k, x - 0.85, fl + 0.77, zIn - 1.0, 0.06)
    papers(k, x + 0.3, fl + 0.77, zIn - 0.95, 0.4, 0.3, 0.18)
    piece('куртка', 'small', () => k.cloth.boxOn(0.44, 0.5, 0.1, x, fl + 0.72, zIn - 2.38))
  }
  // Шкафы с документацией и стол посреди зала.
  for (let i = 0; i < 4; i++)
    piece('шкаф', 'furn', () => k.metal.boxOn(0.55, 2.0, 0.9, x0 + o.wallT + 0.3, fl, z0 + 2.5 + i * 1.1))
  const cx = (x0 + x1) / 2
  const cz = (z0 + z1) / 2
  piece('стол', 'furn', () => {
    k.metal.boxOn(2.6, 0.06, 1.2, cx, fl + 0.76, cz)
    for (const dx of [-1.15, 1.15])
      for (const dz of [-0.5, 0.5]) k.metal.pipe(0.04, 0.76, cx + dx, fl, cz + dz, 5)
  })
  // На большом столе — разложенная карта района и придавившие её кружки.
  piece('карта', 'small', () => k.paper.boxOn(1.5, 0.012, 0.9, cx, fl + 0.82, cz))
  mug(k, cx - 0.6, fl + 0.83, cz + 0.3)
  mug(k, cx + 0.55, fl + 0.83, cz - 0.25)
  papers(k, cx + 0.9, fl + 0.82, cz + 0.35, 0.32, 0.24, -0.25)
  // Карта побольше на стене — то, на что здесь смотрят стоя. Вплотную к стене
  // и ЗА шкафами по Z: на 63 см от стены она висела в воздухе поперёк комнаты.
  sheet(k, x0 + o.wallT + 0.02, fl + 1.9, z0 + 7.4, 1.2, 0.86, 'x')
  // Свет погашен: лента окон операторской была вторым тёплым пятном кадра,
  // и именно она сильнее всего говорила «здесь работают». Плафоны остались
  // тёмными коробками, а комнату держат сумерки, идущие ОТ ЛЕНТЫ ОКОН —
  // источники стоят у самого стекла, а не под потолком.
  for (const lx of [x0 + 4, x1 - 4]) {
    piece('плафон', 'light', () => {
      k.metal.pipe(0.02, 0.24, lx, floor + o.h - 0.28, cz, 5)
      k.dark.box(0.5, 0.12, 0.5, lx, floor + o.h - 0.28, cz)
    })
    dusk(group, lx, floor + 2.6, z1 - 2, 3.4, 14)
  }
}

/**
 * Вестибюль обсерватории: сюда входят с мороза и здесь раздеваются.
 *
 * До фазы 8 он был пуст на 91 % площади — самое большое помещение станции
 * и совершенно нежилое. Тамбур с вешалкой и скамьёй объясняет, зачем он.
 *
 * Фаза 9 добавила второй смысл: вестибюль — не только раздевалка, но и склад
 * всего, что подняли снизу по лестнице. Отсюда бочки, мешки, стеллаж и
 * волокуша; отсюда же конторка с лампой — единственное место станции, где
 * человек сидит лицом к входной двери.
 *
 * Свободного пола он держал 88 % при 17 × 15 м, и это читалось не простором,
 * а недостроенностью: помещение размером с спортзал, в котором стоят скамья
 * и три ящика. Занимать при этом можно только периметр — диагональ от двери
 * к подножию марша обязана остаться коридором.
 */
export function furnishLobby(
  k: Kit,
  o: { x0: number; x1: number; z0: number; z1: number; floor: number; doorX: number; stairX: number },
  group: THREE.Group,
): void {
  const fl = o.floor + 0.02
  // Вешалка и скамья по стене справа от входа — но не в створе марша.
  const wx = o.x1 - 0.5
  piece('вешалка', 'hang', () => {
    k.metal.strut(0.04, wx, o.floor + 2.2, o.z1 - 4.4, wx, o.floor + 2.2, o.z1 - 2.0)
    for (let i = 0; i < 4; i++) k.metal.pipe(0.02, 0.16, wx, o.floor + 2.04, o.z1 - 4.1 + i * 0.7, 4)
  })
  for (const dz of [-4.1, -3.4, -2.0]) coat(k, wx, o.floor + 2.04, o.z1 + dz)
  piece('скамья', 'furn', () => {
    k.metal.boxOn(0.5, 0.06, 2.4, wx - 0.15, fl + 0.45, o.z1 - 3.2)
    for (const dz of [-1.0, 1.0]) k.metal.pipe(0.04, 0.45, wx - 0.15, fl, o.z1 - 3.2 + dz, 5)
  })
  for (let i = 0; i < 2; i++)
    piece('сапоги', 'small', () => k.dark.pipe(0.13, 0.42, wx - 0.5, fl, o.z1 - 3.9 + i * 0.34, 6))
  blot(k, o.doorX, fl, o.z1 - 1.6, 0.9) // натоптанное у двери
  // Ящики у левой стены, со стороны входа: сюда сгружают привезённое снизу.
  // Дальний угол занимать нельзя — там подножие марша в зал (`stairX`).
  for (let i = 0; i < 3; i++) crate(k, o.x0 + 1.2 + i * 0.75, fl, o.z1 - 3.5, 0.62, 0.44, 0.5, i * 0.3)
  crate(k, o.x0 + 1.6, fl + 0.44, o.z1 - 3.5, 0.5, 0.36, 0.42, 0.15)
  piece('ведро', 'small', () => k.metal.pipe(0.16, 0.3, o.x0 + 3.1, fl, o.z1 - 4.2, 7))
  sheet(k, o.x0 + 0.02, fl + 1.6, o.z1 - 2.2, 0.44, 0.6, 'x')

  // --- Вахта у входа ----------------------------------------------------------
  // Конторка стоит у входной стены, лицом в помещение, и НЕ в створе двери:
  // 4 м в сторону от проёма. Столешница выше обычной (0.95 против 0.75) —
  // за такой стоят, а не сидят, и именно этим конторка отличается от стола.
  const kx = o.doorX - 4.0
  // Отступ от стены — 1.6 м, а не 0.95: за конторкой стоит человек, и место
  // для него должно быть с той стороны, где стена, иначе табурет оказывается
  // со стороны посетителя и вахта сидит лицом к бетону.
  const kz = o.z1 - 1.6
  piece('конторка', 'furn', () => {
    k.wood.boxOn(1.7, 0.9, 0.62, kx, fl, kz)
    k.wood.boxOn(1.85, 0.06, 0.74, kx, fl + 0.9, kz)
  })
  const ktop = fl + 0.96
  papers(k, kx - 0.35, ktop, kz, 0.4, 0.3, -0.1) // журнал прихода-ухода
  mug(k, kx + 0.42, ktop, kz - 0.1)
  blot(k, kx + 0.42, ktop, kz - 0.1, 0.06)
  piece('табурет', 'furn', () => {
    k.metal.pipe(0.05, 0.52, kx + 0.15, fl, kz + 0.85, 6)
    k.metal.boxOn(0.36, 0.05, 0.36, kx + 0.15, fl + 0.52, kz + 0.85)
  })
  // Лампа на конторке погасла вместе со станцией. Предмет остался: тёмная
  // настольная лампа над раскрытым журналом читается сильнее, чем её
  // отсутствие, — вещь на месте, а того, кто её включал, нет.
  piece('лампа', 'light', () => {
    k.metal.pipe(0.03, 0.34, kx - 0.72, ktop, kz - 0.12, 5)
    k.dark.box(0.16, 0.09, 0.16, kx - 0.72, ktop + 0.34, kz - 0.12)
  })

  // Пожарный щит справа от двери: щит на стене, огнетушитель и ящик с песком
  // под ним. Обязательная часть любой станции и самый дешёвый способ показать,
  // что помещением пользуются по правилам.
  const fx = o.doorX + 2.4
  piece('щит', 'hang', () => {
    k.dark.box(0.9, 1.0, 0.14, fx, fl + 1.55, o.z1 - 0.09)
    k.metal.box(0.86, 0.05, 0.16, fx, fl + 1.05, o.z1 - 0.09)
  })
  piece('огнетушитель', 'small', () => {
    k.dark.pipe(0.09, 0.46, fx - 0.3, fl, o.z1 - 0.35, 8)
    k.metal.box(0.15, 0.07, 0.15, fx - 0.3, fl + 0.44, o.z1 - 0.35)
  })
  piece('ящик с песком', 'furn', () => {
    k.dark.boxOn(0.8, 0.6, 0.55, fx + 0.4, fl, o.z1 - 0.4)
    k.metal.boxOn(0.86, 0.05, 0.6, fx + 0.4, fl + 0.6, o.z1 - 0.4)
  })

  // Лопаты и метла в углу у входа: черенки под наклоном к стене. Наклон задан
  // ДВУМЯ ТОЧКАМИ (`strut`), а не поворотом — правило фазы 4: Эйлер собирается
  // XYZ, и наклонённый плюс повёрнутый предмет уезжает вокруг мировой оси.
  for (let i = 0; i < 3; i++) {
    const sx = o.x0 + 0.75 + i * 0.3
    const sz = o.z1 - 1.5 - i * 0.22
    piece('лопата', 'small', () => {
      k.metal.strut(0.026, sx, fl, sz, sx + 0.42, fl + 1.62, sz + 0.08, 5)
      if (i < 2) k.metal.boxOn(0.28, 0.06, 0.24, sx, fl, sz)
      else k.cloth.boxOn(0.2, 0.3, 0.16, sx, fl, sz) // третья — метла
    })
  }

  // --- Склад привезённого -----------------------------------------------------
  // Всё у дальней стены и у правой: диагональ «дверь → подножие марша» держим
  // пустой, иначе через вестибюль придётся ходить в обход.
  for (let i = 0; i < 5; i++)
    piece('бочка', 'furn', () =>
      k.rust.pipe(0.32, 0.88, o.doorX - 1.4 + i * 0.72, fl, o.z0 + 0.62 + (i % 2) * 0.18, 10),
    )
  // Контейнер и штабель поддонов: помещению 17 × 15 м при потолке 5.3 нужен
  // хоть один предмет ростом с человека, иначе всё, что стоит по стенам,
  // читается мелочью на дне бетонной коробки и зал кажется недостроенным.
  piece('контейнер', 'furn', () => {
    k.rust.boxOn(1.3, 1.5, 1.1, o.doorX - 4.4, fl, o.z0 + 0.95)
    for (const dy of [0.35, 1.05])
      k.metal.box(1.34, 0.07, 1.14, o.doorX - 4.4, fl + dy, o.z0 + 0.95)
  })
  piece('поддоны', 'furn', () => {
    for (let i = 0; i < 4; i++)
      k.wood.boxOn(1.2, 0.11, 0.9, o.doorX - 6.6, fl + i * 0.13, o.z0 + 0.85, 0.04 * i)
  })
  // Мешки штабелем — единственная «мягкая» форма помещения: три куска под
  // разными углами, иначе штабель читается коробками (правило куртки).
  //
  // Стоят в промежутке между контейнером и поддонами, и место тут считанное:
  // от правого края поддонов до левого бока контейнера меньше метра. Прежний
  // штабель (`doorX − 5.2`) этой меры не знал и на треть входил контейнеру
  // в бок — жёсткий ящик, сквозь который торчит мешковина. Заодно разъехались
  // и сами мешки: два нижних лежали в одной точке с разницей 12 см, то есть
  // один внутри другого, и мягкая куча читалась одним мешком.
  for (const [dx, dz, dy, ry] of [
    [0, 0, 0, 0.2],
    [0.08, 0.5, 0, -0.15],
    [0, 0.25, 0.3, -0.5],
  ] as const)
    piece('мешок', 'small', () =>
      k.cloth.boxOn(0.62, 0.3, 0.44, o.doorX - 5.55 + dx, fl + dy, o.z0 + 0.55 + dz, ry),
    )
  const sx = o.x1 - 0.3
  piece('стеллаж', 'furn', () => {
    k.metal.boxOn(0.5, 2.0, 2.6, sx, fl, o.z1 - 10.6)
    // Вылет полки - 2 см, см. стеллажи мастерской.
    for (let i = 1; i < 4; i++) k.dark.box(0.54, 0.05, 2.5, sx, fl + i * 0.5, o.z1 - 10.6)
  })
  for (let i = 0; i < 4; i++)
    crate(k, sx, fl + 0.5 + (i % 3) * 0.5, o.z1 - 11.6 + i * 0.62, 0.36, 0.26, 0.32, i * 0.2)
  // Волокуша: на ней тянут груз от верха лестницы. Стоит у левой стены,
  // прислонённая, — поэтому полозья идут наклонно двумя точками.
  piece('волокуша', 'furn', () => {
    const vx = o.x0 + 0.5
    const vz = o.z1 - 7.4
    for (const d of [-0.34, 0.34]) {
      k.metal.strut(0.035, vx, fl, vz + d, vx + 0.62, fl + 1.5, vz + d, 5)
      k.metal.strut(0.025, vx + 0.1, fl + 0.24, vz + d, vx + 0.55, fl + 1.3, vz + d, 4)
    }
    for (let i = 0; i < 3; i++) {
      const t = 0.15 + i * 0.3
      k.metal.strut(0.022, vx + t * 0.62, fl + t * 1.5, vz - 0.34, vx + t * 0.62, fl + t * 1.5, vz + 0.34, 4)
    }
  })

  // Радиатор у стены, где раздеваются, и труба, которая его питает: она же
  // связывает взглядом входную стену с дальней и объясняет, откуда тут тепло.
  piece('радиатор', 'hang', () => {
    for (let i = 0; i < 8; i++) k.metal.pipe(0.05, 0.72, o.x1 - 0.2, fl + 0.28, o.z1 - 6.4 + i * 0.16, 5)
  })
  // Труба и спуск к радиатору — ДВА предмета. Внутри одного рамка растягивалась
  // от потолка до радиатора по всей одиннадцатиметровой длине трубы, и
  // `npm run room` находил её «в одном месте» со стеллажом у той же стены.
  piece('труба отопления', 'hang', () =>
    k.metal.box(0.1, 0.1, 11.0, o.x1 - 0.22, fl + 3.4, o.z1 - 7.0),
  )
  piece('спуск к радиатору', 'hang', () =>
    k.metal.strut(0.05, o.x1 - 0.22, fl + 3.35, o.z1 - 6.3, o.x1 - 0.22, fl + 1.05, o.z1 - 6.3, 5),
  )

  // Бак с водой у той же стены: водопровода на гребне нет, воду топят из снега
  // и держат в баке с краном. Кран — единственная деталь, которая делает
  // цилиндр баком, а не бочкой.
  piece('бак', 'furn', () => {
    k.rust.pipe(0.5, 1.2, o.x1 - 0.75, fl, o.z1 - 8.3, 12)
    k.rust.pipe(0.52, 0.06, o.x1 - 0.75, fl + 1.2, o.z1 - 8.3, 12)
    // Кран НАД краем ведра, а не в нём. На прежних 0.35 носик приходился
    // ровно на бортик (ведро высотой 0.32) и входил в стенку на десять
    // сантиметров: под краном стояло проткнутое ведро.
    k.dark.box(0.16, 0.1, 0.1, o.x1 - 1.3, fl + 0.46, o.z1 - 8.3)
  })
  piece('ведро', 'small', () => k.metal.pipe(0.17, 0.32, o.x1 - 1.45, fl, o.z1 - 8.3, 8))

  // Штабель ящиков в дальнем углу и стол разбора у левой стены за маршем:
  // привезённое снизу сначала кладут на стол, потом растаскивают по местам.
  for (let i = 0; i < 3; i++)
    crate(k, o.x1 - 1.1 - (i % 2) * 0.7, fl + Math.floor(i / 2) * 0.44, o.z0 + 1.6 + i * 0.2, 0.62, 0.44, 0.5, i * 0.25)
  {
    const tx = o.x0 + 0.8
    const tz = o.z0 + 3.8
    piece('стол', 'furn', () => {
      k.metal.boxOn(0.8, 0.06, 1.8, tx, fl + 0.78, tz)
      for (const dz of [-0.75, 0.75])
        for (const dx of [-0.3, 0.3]) k.metal.pipe(0.035, 0.78, tx + dx, fl, tz + dz, 5)
    })
    papers(k, tx, fl + 0.84, tz - 0.4, 0.34, 0.26, 0.2)
    piece('фонарь', 'small', () => {
      k.dark.pipe(0.07, 0.2, tx + 0.15, fl + 0.84, tz + 0.5, 8)
      k.metal.pipe(0.075, 0.05, tx + 0.15, fl + 1.04, tz + 0.5, 8)
    })
  }
  // На скамье — вещи, которые здесь оставили. Отметка ровно по верху скамьи
  // (`fl + 0.51`): двух сантиметров зазора хватает, чтобы `npm run room`
  // объявил предмет висящим в воздухе, — опора ищется попаданием низа
  // в размах опоры, а не близостью к ней.
  piece('термос', 'small', () => {
    k.enamel.pipe(0.055, 0.26, o.x1 - 0.65, fl + 0.5, o.z1 - 2.4, 8)
    k.metal.pipe(0.05, 0.04, o.x1 - 0.65, fl + 0.76, o.z1 - 2.4, 8)
  })
  piece('рукавицы', 'small', () => k.cloth.boxOn(0.24, 0.06, 0.18, o.x1 - 0.62, fl + 0.5, o.z1 - 3.9))
}

/** Зал обсерватории: рабочее место у телескопа и стремянка к окуляру. */
export function furnishDomeHall(
  k: Kit,
  o: { x: number; z: number; floor: number; r: number },
  warm: Warm[],
): void {
  const { x, z, floor } = o
  const dx = x + 4.4
  piece('пульт', 'furn', () => {
    k.metal.boxOn(1.4, 0.9, 0.7, dx, floor, z + 1.2)
    for (let i = 0; i < 3; i++) k.hot.box(0.06, 0.06, 0.03, dx - 0.3 + i * 0.3, floor + 0.95, z + 0.86)
  })
  piece('стул', 'furn', () => {
    k.metal.pipe(0.05, 0.55, dx, floor, z + 2.3, 6)
    k.metal.boxOn(0.45, 0.05, 0.45, dx, floor + 0.55, z + 2.3)
  })
  // Плед на стуле, кружка и журнал наблюдений на пульте: в куполе холодно,
  // а сидеть в нём приходится ночь напролёт.
  piece('плед', 'small', () => k.cloth.boxOn(0.42, 0.12, 0.4, dx, floor + 0.6, z + 2.3))
  mug(k, dx - 0.45, floor + 0.92, z + 1.2)
  papers(k, dx + 0.25, floor + 0.92, z + 1.15, 0.36, 0.26, 0.22)
  // Настольная лампа не горит: наблюдений здесь не ведут давно. Плед на стуле
  // и кружка на пульте остались — вещи переживают тех, кто ими пользовался,
  // и в этом вся история зала.
  piece('лампа', 'light', () => {
    k.metal.pipe(0.03, 0.32, dx + 0.55, floor + 0.92, z + 1.35, 5)
    k.dark.box(0.14, 0.08, 0.14, dx + 0.55, floor + 1.2, z + 1.35)
  })
  // Стремянка к окуляру и ящик с кассетами у тумбы телескопа.
  piece('стремянка', 'furn', () => {
    const sx = x - 2.3
    const sz = z + 1.9
    for (const d of [-0.24, 0.24]) k.metal.strut(0.03, sx, floor, sz + d, sx + 0.5, floor + 1.6, sz + d)
    for (let i = 1; i <= 4; i++) {
      const t = i / 5
      k.metal.strut(0.022, sx + t * 0.5, floor + t * 1.6, sz - 0.24, sx + t * 0.5, floor + t * 1.6, sz + 0.24)
    }
  })
  crate(k, x - 1.2, floor, z - 2.4, 0.55, 0.4, 0.45, 0.4)
  // Чехол телескопа, сброшенный на ящик: его снимают на ночь и кладут рядом.
  piece('чехол', 'small', () => {
    k.cloth.boxOn(0.5, 0.16, 0.4, x - 1.2, floor + 0.4, z - 2.4, 0.4)
    k.cloth.boxOn(0.3, 0.12, 0.26, x - 0.95, floor + 0.5, z - 2.25, -0.3)
  })

  // --- Место у стены барабана ---------------------------------------------------
  // Зал — единственное КРУГЛОЕ помещение станции, и расставлять в нём надо по
  // двум правилам, оба нашлись счётом за один запуск `npm run room`:
  //
  //   1) вплотную к стене можно только в диагональных секторах. Рамка
  //      помещения — описанный квадрат, и по осям она кончается там же, где
  //      стена, а по диагоналям запас есть: угол квадрата лежит в 1.41 радиуса.
  //   2) запас до стены считается по ОСЕВОЙ рамке предмета, а не по его
  //      настоящим углам. Реестр (`fixtures.ts`) снимает с геометрии
  //      bounding box, повёрнутого габарита в нём нет: поставленный по
  //      касательной верстак реально стоит в 30 см от стены, а рамка
  //      уходит за неё на 71 см — и проверка права, потому что дальше по
  //      этой рамке считают все, включая её.
  // Отсюда: предметы стоят ПО ОСЯМ, сдвинутые в диагональный сектор. Числа
  // ниже подобраны так, что дальний угол рамки остаётся внутри 8.5 при стене
  // 8.6, - правило живёт в них, отдельной константы под него нет.

  // Привод вращения купола: редуктор, вал к рельсу и маховик, которым купол
  // доворачивают руками. Он объясняет, как эта крыша открывается, — без него
  // щель в куполе просто нарисована.
  {
    const ax = x + 5.2
    const az = z + 5.4
    piece('привод купола', 'furn', () => {
      k.dark.boxOn(0.8, 1.05, 0.8, ax, floor, az)
      k.metal.pipe(0.07, 4.2, ax, floor + 1.05, az, 8)
      // Маховик стоит вертикально, и поворот запечён в геометрию: правило
      // фазы 4 — наклон через `rx/rz` уезжает вокруг мировой оси.
      const wheel = new THREE.CylinderGeometry(0.33, 0.33, 0.07, 16)
      wheel.rotateZ(Math.PI / 2)
      k.metal.add(wheel, ax - 0.62, floor + 1.15, az)
      k.metal.strut(0.03, ax - 0.6, floor + 1.15, az, ax, floor + 1.15, az, 5)
    })
    // Шкаф управления рядом. Кабель от него к приводу — ОТДЕЛЬНЫЙ предмет,
    // и это не мелочь: внутри `piece` шкафа его рамка растягивалась до самого
    // привода, и `npm run room` честно объявлял два предмета в одном месте.
    // Всё, что от предмета отходит, живёт своим габаритом.
    const sx = x + 6.3
    const sz = z + 4.2
    piece('шкаф управления', 'furn', () => {
      k.metal.boxOn(0.45, 1.6, 0.7, sx, floor, sz)
      for (let i = 0; i < 3; i++) k.hot.box(0.04, 0.04, 0.03, sx - 0.24, floor + 1.2 + i * 0.14, sz - 0.16)
    })
    piece('кабель', 'small', () => k.metal.strut(0.03, sx, floor + 0.03, sz, ax, floor + 0.03, az, 4))
  }

  // Стеллаж с кассетами и журналами наблюдений: то, ради чего в этот зал
  // вообще приходят с бумагой.
  {
    const sx = x + 5.1
    const sz = z - 5.2
    piece('стеллаж', 'furn', () => {
      k.metal.boxOn(0.5, 1.9, 2.4, sx, floor, sz)
      for (let i = 1; i < 4; i++) k.dark.box(0.52, 0.05, 2.3, sx, floor + i * 0.47, sz)
    })
    for (let i = 0; i < 4; i++)
      crate(k, sx, floor + 0.47 + (i % 3) * 0.47, sz - 0.85 + i * 0.55, 0.34, 0.24, 0.3, i * 0.2)
    papers(k, sx, floor + 1.41, sz, 0.3, 0.22, 0.15)
  }

  // Верстак для юстировки: зеркало и окуляры правят здесь же, не унося вниз.
  {
    const bx = x - 5.2
    const bz = z + 5.0
    piece('верстак', 'furn', () => {
      k.wood.boxOn(0.85, 0.05, 2.2, bx, floor + 0.85, bz)
      for (const dz2 of [-0.9, 0.9])
        for (const dx2 of [-0.32, 0.32]) k.metal.pipe(0.04, 0.85, bx + dx2, floor, bz + dz2, 5)
    })
    for (const [dz2, len] of [
      [-0.6, 0.3],
      [0.15, 0.22],
    ] as const) {
      piece('инструмент', 'small', () => k.metal.boxOn(0.07, 0.035, len, bx + 0.1, floor + 0.9, bz + dz2))
    }
    piece('ветошь', 'small', () => k.cloth.boxOn(0.26, 0.06, 0.3, bx - 0.15, floor + 0.9, bz + 0.65))
    // Бухта кабеля у верстака: две щеки и барабан, как у катушки на дорожке.
    piece('бухта', 'small', () => {
      for (const dz2 of [-0.14, 0.14]) {
        const cheek = new THREE.CylinderGeometry(0.3, 0.3, 0.05, 12)
        cheek.rotateX(Math.PI / 2)
        k.dark.add(cheek, x - 6.0, floor + 0.3, z + 4.3 + dz2)
      }
    })
  }

  // Обогреватель у рабочего места — не у стены: греют человека, а не зал.
  // В куполе холодно по замыслу (щель открыта), и плед на стуле объясняется
  // ровно тем, что этой печки на 16 метров диаметра не хватает.
  piece('обогреватель', 'furn', () => {
    for (let i = 0; i < 6; i++) k.dark.pipe(0.055, 0.6, dx + 1.5, floor, z + 0.1 + i * 0.14, 5)
    k.metal.box(0.34, 0.06, 0.9, dx + 1.5, floor + 0.63, z + 0.45)
  })
  // Хронометр на пульте: в обсерватории время — рабочий инструмент.
  piece('хронометр', 'small', () => {
    k.dark.boxOn(0.16, 0.14, 0.1, dx - 0.15, floor + 0.92, z + 1.45)
    k.paper.box(0.12, 0.11, 0.012, dx - 0.15, floor + 1.0, z + 1.39)
  })
  // Ведро под капель и тряпка рядом: щель купола не герметична, и в оттепель
  // с рельса течёт. Мелочь, но объясняет, почему пол здесь мокрый.
  {
    const wx = x - 2.4
    const wz = z + 6.6
    piece('ведро', 'small', () => k.metal.pipe(0.17, 0.32, wx, floor, wz, 8))
    piece('тряпка', 'small', () => k.cloth.boxOn(0.3, 0.05, 0.26, wx + 0.45, floor, wz + 0.2, 0.3))
    blot(k, wx + 0.3, floor, wz + 0.1, 0.4)
  }
}
