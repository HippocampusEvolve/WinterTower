/**
 * Окна фасада служебного корпуса.
 *
 * Живут здесь по общему правилу файла: с фазы 8 окно — это ПРОЁМ в стене,
 * а не наклейка поверх неё. Значит одни и те же числа нужны в двух местах —
 * тому, кто режет стену (`wall` в `wingSection`), и тому, кто ставит в проём
 * стекло с рамой. Разъедутся эти два места — и в стене появится дыра,
 * не закрытая стеклом, или стекло, вмурованное в бетон.
 *
 * `mid` — центр окна над полом секции.
 */
export const WING_WIN = { w: 1.7, h: 1.3, mid: 2.2, step: 3.4, edge: 2.6 }

/** Где стоят окна секции. `n` — номер по порядку, от него зависит сорт стекла. */
export function wingWindows(i: number): { z: number; n: number }[] {
  const s = WING[i]
  const out: { z: number; n: number }[] = []
  let n = 0
  for (let z = s.z0 + WING_WIN.edge; z <= s.z1 - WING_WIN.edge; z += WING_WIN.step, n++) {
    // Окно в дверном проёме — это не окно, а дыра в стене насквозь.
    if (i === WING_PLAN.entry.wing && Math.abs(z - WING_PLAN.entry.z) < 1.7) continue
    out.push({ z, n })
  }
  return out
}

