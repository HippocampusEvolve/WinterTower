/** Ширина свободного коридора по обе стороны от оси дорожки. */
export const CORRIDOR = PATH_W / 2 + 1.2

/** Насколько точка (x,z) внутри пятна, с запасом `pad`. Отрицательное — снаружи. */
export function insideBy(s: Spot, x: number, z: number, pad = 0): number {
  return Math.min(x - (s.x0 - pad), s.x1 + pad - x, z - (s.z0 - pad), s.z1 + pad - z)
}

/**
 * Куда сходят на землю три оттяжки решётчатой мачты.
 *
 * Живёт здесь, а не в `props.ts`, по общему правилу файла: расстановка —
 * это числа, и проверка обязана читать ТЕ ЖЕ числа, а не их копию. До фазы 7
 * азимуты назначались тремя равными долями круга, и средний анкер садился
 * в точку (7.6, −57.8) — внутри пятна центрального корпуса. Снаружи кадр
 * выглядел безупречно, а изнутри операторской трос шёл по диагонали через
 * комнату: анкер стоял у неё на полу, трос протыкал крышу. Ни одна проверка
 * этого не видела — они знали про положение мачты, но не про её тросы.
 *
 * Азимут поэтому не назначается, а выбирается: ближайший к задуманному,
 * свободный от пятен и от дорожки.
 *
 * Свободным считается ВЕСЬ трос, а не его конец. Анкер за углом здания —
 * это ещё не чистый трос: отрезок от мачты к нему срезает угол по диагонали,
 * и внутри комнаты видно ровно то же самое. Поэтому проба идёт по всей длине.
 */
export function guyAnchors(): [number, number][] {
  const R = 9.5
  const out: [number, number][] = []
  for (let k = 0; k < 3; k++) {
    const a0 = (k / 3) * Math.PI * 2 + 0.6
    // Полный круг, а не сектор. Первая версия перебирала ±0.77 рад и на средней
    // оттяжке не находила НИЧЕГО: свободный азимут там лежит в 0.99 рад. Цикл
    // тихо возвращал последнюю пробу — то есть занятую точку. Проверка молчала,
    // потому что край пятна проходил ровно между её запасом и запасом перебора.
    let a = a0
    let found = false
    for (let step = 0; step <= 58 && !found; step++) {
      // Влево-вправо по очереди: анкер уезжает от задуманного места минимально.
      a = a0 + (step % 2 ? -1 : 1) * Math.ceil(step / 2) * 0.11
      found = guyClear(a, R)
    }
    out.push([LATTICE.x + Math.cos(a) * R, LATTICE.z + Math.sin(a) * R])
  }
  return out
}

/** Свободен ли трос целиком: от мачты до анкера по азимуту `a`, радиус `R`. */
function guyClear(a: number, R: number): boolean {
  for (let t = 0.15; t <= 1.0001; t += 0.085) {
    const x = LATTICE.x + Math.cos(a) * R * t
    const z = LATTICE.z + Math.sin(a) * R * t
    if (SPOTS.some((s) => insideBy(s, x, z, 1.2) > 0)) return false
    if (PATH.some(([px, pz]) => Math.hypot(x - px, z - pz) < CORRIDOR)) return false
  }
  return true
}
