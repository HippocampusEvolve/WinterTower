/**
 * lake.ts — замёрзшее озеро под гребнем и вмёрзшая в него лодка.
 *
 * Зачем оно есть. До него слева от станции был обрыв в никуда: земля падала
 * 1.7 м на метр и уходила за −120 м, а главная лестница кончалась над пустотой.
 * Спуск никуда не вёл, и весь левый край кадра был «мимо мира».
 *
 * Как сделано. Само дно задаёт рельеф: `heightAt` берёт максимум с `LAKE.y`
 * (см. `terrain.ts`), поэтому берег получается там, где склон сам пересекает
 * отметку воды, — изрезанный, без единой лишней константы. Здесь только
 * поверхность льда и то, что на ней стоит.
 *
 * Почему лёд — отдельная поверхность, а не цвет вершин рельефа. Лёд читается
 * льдом ровно потому, что он ЗЕРКАЛО: гладкий, ловит светящееся небо и потому
 * темнее снега рядом. Материал земли матовый (roughness 0.94), и на нём озеро
 * выходило белым полем, неотличимым от заснеженного плато.
 *
 * Плоскость лежит на 3 см выше отметки воды и накрывает весь мир. Прятать её
 * по контуру берега не нужно: там, где земля выше, она сама её и закрывает —
 * игрок всегда смотрит на мир сверху.
 */

import * as THREE from 'three'
import { MAT } from './materials'
import { Parts, rng } from './parts'
import { LAKE } from './layout'
import { heightAt } from './terrain'

/** Размер полотна льда: то же, что у рельефа, минус запас на кромку. */
const SIZE = 440
const CENTER_Z = -60

export function buildLake(): { ice: THREE.Mesh; props: THREE.Group } {
  const geo = new THREE.PlaneGeometry(SIZE, SIZE, 1, 1)
  geo.rotateX(-Math.PI / 2)
  geo.translate(0, LAKE.y + 0.03, CENTER_Z)
  const ice = new THREE.Mesh(geo, MAT.ice)
  ice.name = 'lake-ice'

  const group = new THREE.Group()
  group.name = 'lake-props'

  const hull = new Parts()
  const trim = new Parts()
  const snow = new Parts()
  const b = LAKE.boat
  const y = LAKE.y

  // --- Лодка ------------------------------------------------------------------
  // Вмёрзла с креном: ровно стоящая лодка читается моделькой на подставке,
  // а накренённая — брошенной. Осадка тоже не нулевая, лёд встал вокруг корпуса.
  // Осадка мелкая нарочно. Утопленная по планширь лодка честнее — она вмёрзла
  // осенью, лёд встал вокруг, — но с десяти метров над льдом торчит 30 см борта,
  // и предмет читается доской. Оставляем надводный борт 0.6 м: лодка здесь
  // работает масштабной линейкой, а линейка обязана быть видна.
  const sit = -0.1
  const cos = Math.cos(b.angle)
  const sin = Math.sin(b.angle)
  /** Из локальных координат лодки (вдоль корпуса, поперёк) в мировые. */
  const at = (u: number, v: number): [number, number] => [
    b.x + u * cos - v * sin,
    b.z + u * sin + v * cos,
  ]

  // Днище и борта: борта наклонены наружу, иначе корпус читается ящиком.
  //
  // Наклон запекается В ГЕОМЕТРИЮ (`geo.rotateX`), а не передаётся в `add`.
  // `Parts.add` собирает Эйлера в порядке XYZ, то есть рыскание применяется
  // РАНЬШЕ наклона, и наклон выходит вокруг мировой оси, а не вокруг оси
  // корпуса. Лодка от этого разваливается в кучу досок — проверено.
  hull.box(b.len, 0.24, b.beam * 0.78, b.x, y + sit + 0.12, b.z, -b.angle)
  for (const s of [-1, 1]) {
    const side = new THREE.BoxGeometry(b.len * 0.94, 0.8, 0.1)
    side.rotateX(s * 0.2)
    const [sx, sz] = at(0, (s * b.beam) / 2)
    hull.add(side, sx, y + sit + 0.5, sz, 0, -b.angle, 0)
  }
  // Нос и корма: клинья, сходящиеся к штевню. Завал штевня тоже в геометрию.
  for (const s of [-1, 1]) {
    const stem = new THREE.BoxGeometry(0.95, 0.86, b.beam * 0.5)
    stem.rotateZ(s * 0.32)
    const [ex, ez] = at((s * b.len) / 2, 0)
    hull.add(stem, ex, y + sit + 0.52, ez, 0, -b.angle, 0)
  }
  // Планширь: светлая кромка по борту. Она и рисует силуэт лодки — без неё
  // корпус в тумане сливается в тёмное пятно.
  for (const s of [-1, 1]) {
    const [sx, sz] = at(0, (s * b.beam) / 2)
    trim.add(new THREE.BoxGeometry(b.len * 0.95, 0.09, 0.2), sx, y + sit + 0.88, sz, 0, -b.angle, 0)
  }
  // Банки: две поперечные доски. Без них внутри пусто, и корпус читается корытом.
  for (const u of [-b.len * 0.18, b.len * 0.22]) {
    const [tx, tz] = at(u, 0)
    trim.box(0.3, 0.08, b.beam * 0.9, tx, y + sit + 0.66, tz, -b.angle)
  }
  // Весло, брошенное поперёк борта.
  {
    const [ax, az] = at(-0.7, -b.beam * 0.85)
    const [bx2, bz2] = at(1.9, b.beam * 0.6)
    trim.strut(0.05, ax, y + sit + 0.95, az, bx2, y + sit + 0.7, bz2)
  }
  // TODO: снег внутри лодки и нанос к наветренному борту. Замысел есть,
  // геометрии нет - прежний блок считал две точки и молча их выбрасывал.

  // --- Вешки во льду ----------------------------------------------------------
  // Ряд кольев, каким метят зимник: они дают глубину пустой плоскости
  // и намекают, что по озеру ходят.
  const rand = rng(4711)
  for (let i = 0; i < 9; i++) {
    const t = i / 8
    const x = b.x - 6 - t * 46 + (rand() - 0.5) * 3
    const z = b.z + 2 + t * 22 + (rand() - 0.5) * 3
    if (heightAt(x, z) > LAKE.y + 0.05) continue // на берег вешки не ставим
    const h = 1.1 + rand() * 0.5
    trim.pipe(0.05, h, x, y, z, 5)
    // Нижняя грань наноса не совпадает с подошвой вешки на льду. Небольшой
    // нахлёст остаётся внутри снега, видимая верхняя поверхность не меняется.
    snow.box(0.5, 0.1, 0.5, x, y + 0.062, z, rand() * 3)
  }

  group.add(hull.mesh(MAT.boat, 'boat-hull'))
  group.add(trim.mesh(MAT.metalDark, 'boat-trim'))
  group.add(snow.mesh(MAT.snow, 'boat-snow'))
  return { ice, props: group }
}
